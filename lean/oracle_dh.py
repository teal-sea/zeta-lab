import sys
from fractions import Fraction
import mpmath
from mpmath import iv, mp

# Set high precision for the oracle
mp.dps = 50
iv.prec = 128

def generate_lean_certificate():
    sigma = Fraction(808517, 1000000)
    tau = Fraction(85699348, 1000000)
    s = mp.mpc(float(sigma), float(tau))
    
    lean_code = f"""import Mathlib
import ZetaLean.Rigor
import ZetaLean.DirichletEval

/-!
# Davenport-Heilbronn Oracle Certificate
This file is generated by `oracle_dh.py`.
It provides the certified bounds for the Davenport-Heilbronn function at the off-line zero.
-/

def offline_zero_re : ℚ := {sigma.numerator} / {sigma.denominator}
def offline_zero_im : ℚ := {tau.numerator} / {tau.denominator}

"""
    # Evaluate first few terms n^(-s) = exp(-s * log(n))
    for n in range(1, 6):
        x = -s * mp.log(n)
        
        # Choose k such that |x / 2^k| <= 1
        x_mag = abs(x)
        k = 0
        while x_mag / (2**k) > 0.9:
            k += 1
            
        x_scaled = x / (2**k)
        
        # Compute Taylor polynomial of degree N=15
        N = 15
        T = mp.mpc(0)
        term = mp.mpc(1)
        for m in range(N):
            T += term
            term = term * x_scaled / (m + 1)
            
        # Error bound for exp(x_scaled)
        x_scaled_mag = abs(x_scaled)
        eps = (x_scaled_mag**N) * (N + 1) / (mp.fac(N) * N)
        
        # Now square the disk k times
        # A disk is center C, radius R
        C = T
        R = eps
        for _ in range(k):
            # (C + r)^2 = C^2 + 2Cr + r^2
            # Max magnitude of error is 2|C|R + R^2
            new_C = C**2
            new_R = 2 * abs(C) * R + R**2
            C = new_C
            R = new_R
            
        re_val = C.real
        im_val = C.imag
        
        re_lb = re_val - R
        re_ub = re_val + R
        im_lb = im_val - R
        im_ub = im_val + R
        
        lean_code += f"""
def term_{n}_bound : BoundedComplex :=
  {{ re_lb := {re_lb},
    re_ub := {re_ub},
    im_lb := {im_lb},
    im_ub := {im_ub},
    re_lb_le_ub := by norm_num,
    im_lb_le_ub := by norm_num }}
"""

    # Generate a tail bound for the remainder of the Dirichlet series (N > 5)
    # The coefficients a_n are bounded by 1 + kappa <= 1.3
    # The tail is bounded by sum_{n=6}^\infty 1.3 * n^{-sigma} <= 1.3 * \int_5^\infty x^{-sigma} dx = 1.3 * 5^{1-sigma} / (sigma - 1)
    # But since sigma = 0.808517 < 1, the Dirichlet series does not converge absolutely!
    # We must use summation by parts, or use the Hurwitz zeta approximation!
    # For Phase B, we just leave a comment in the Lean file.
    lean_code += f"""
/- 
Note: The Dirichlet series for DH(s) does not converge absolutely at Re(s) ≈ 0.808.
To evaluate DH(s) rigorously, we must use the Hurwitz zeta expansion, 
or approximate the analytic continuation. The above bounds are for $n^{{-s}}$.
-/
"""
    
    with open("ZetaLean/OracleDH.lean", "w") as f:
        f.write(lean_code)
    
    print("Certificate generated in ZetaLean/OracleDH.lean")

if __name__ == "__main__":
    generate_lean_certificate()
