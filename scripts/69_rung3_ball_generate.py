def _assembly_block(b: SimpleNamespace) -> str:
    """Block, anti-term, corrected ball, and the site theorem.  Lives in the root."""
    site, kind, sid = b.site, b.kind, b.sid
    K, N, SI, SB = b.K, b.N, b.SI, b.SB
    tail_r, stats = b.tail_r, b.stats
    m1, m2, m3, m4 = b.m1, b.m2, b.m3, b.m4
    pair, block = b.pair, b.block
    five_one_sub, anti_v = b.five_one_sub, b.anti_v
    anti_pair, anti_sum, anti = b.anti_pair, b.anti_sum, b.anti
    corrected, inflated = b.corrected, b.inflated
    lines: list[str] = []
    a = lines.append
    pnames = {m: f"Pow_{sid}_{m}" for m in (m1, m2, m3, m4)}
    pair_expr = f"({pnames[m2]}.add {pnames[m3]}.neg)"
    uk, upair = ball._absc_upper(ball.KAPPA_C), ball._absc_upper(pair)
