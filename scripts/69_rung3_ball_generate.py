    a(f"  norm_num [{', '.join(pnames.values())}, Block_{sid}, kappaBall, ofRealInterval,")
    a("    DH.kappaI, ComplexBall.add, ComplexBall.neg, ComplexBall.mul]")
    a("")

    one_minus = ball.cadd(ball.cexact(1, 0), ball.cneg(b.Sval))
    u_one_minus = ball._absc_upper(one_minus)
    lower5, lower5proof = _lower_norm_proof(
        f"(fiveOneSubBall {SB} {q(u_one_minus)})", five_one_sub,
        f"{SB}, fiveOneSubBall, ComplexBall.exact, ComplexBall.add, ComplexBall.neg, ComplexBall.mul")
    a(f"def AntiV_{sid} : ComplexBall := {lit(anti_v)}")
    a(f"private lemma evV_{sid} :")
