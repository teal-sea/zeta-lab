# G. Lower-order probes S1, S2 (over F) and S3 (over Q(i)), at one prime each
# ---------------------------------------------------------------------------
#
# The referee's own reading of the task's one-line descriptions, written before any
# lane file was opened:
#
#   the paper's probe = cubic theta (coefficient gamma_2 at squarefree c) with the
#   sextic twist chi_A(m) (Poisson-dual Gauss sum gamma_1); its scalar input is
#   gamma_1 gamma_2 = mu alpha G (Equation 4.7);
#   S1 = cubic theta with the conjugate cubic twist chi_A(m)^4 (order k = 3);
#   S2 = cubic theta with the quadratic twist chi_A(m)^3 (order k = 2);
#   S3 = the classical theta over Q(i) (coefficients on squares only) with the
#        quartic residue-symbol twist, the order-two analogue of the paper's pair.
#
# A local value is called scalar when it lies in mu_infinity * alpha(p)^Z: a root of
# unity times an integer power of alpha(p) = p/|p|, the values a Hecke character
# (finite order times an integer infinity type) can take at p.


def alpha_is_root_of_unity(ld: LocalData) -> bool:
    """alpha(p) is a root of unity iff alpha^N = 1 (the roots of unity in Q(zeta_N), N even)."""
    return ld.alpha ** ld.cyc.N == ld.cyc.one


def alpha_exponent(x, alpha, cyc: Cyc, span: int = 36):
    """The rational n with x^12 / alpha^(12 n) a root of unity (12 n in [-span, span]).

    In Q(zeta_N) with N even the roots of unity are mu_N, so y is a root of unity iff
    y^N = 1; with y = x^12 alpha^-a this reads x^(12N) = (alpha^N)^a, tested for each a
    against one power of x and the powers of alpha^N.  None when no a in the span works.
    """
    assert cyc.N % 2 == 0
    target = (x ** 12) ** cyc.N
    aN = alpha ** cyc.N
    if target == cyc.one:
        return Fraction(0)
    up, down = cyc.one, cyc.one
    aNinv = 1 / aN
    for a in range(1, span + 1):
        up = up * aN
        down = down * aNinv
        if target == up:
            return Fraction(a, 12)
        if target == down:
            return Fraction(-a, 12)
    return None


def scalar_exponent(ld: LocalData, x, span: int = 36):
    """The rational n with x^12 / alpha^(12 n) a root of unity, searched over 12n in [-span, span].

    x is scalar (in mu_infinity alpha^Z) exactly when the returned n is an integer.
    Returns None when no such n exists in the span.
    """
    return alpha_exponent(x, ld.alpha, ld.cyc, span)


def twist_products(prime: FPrime) -> dict:
    """theta(p) gamma_e(p) for the cubic theta (gamma_2) and its conjugate (gamma_4).

    The twist chi^e has Poisson-dual Gauss sum gamma_e at A = p.  e = 1 is the paper's
    sextic twist, e = 4 the conjugate cubic (S1), e = 3 the quadratic (S2).
    """
    ld = LocalData(prime)
    cyc = ld.cyc
    assert not alpha_is_root_of_unity(ld) or prime.kind == "inert"
    Gp = cyc.zeta6(-ld.k4) * ld.gamma[3]  # G(p) = conj(chi_p(4)) gamma_3(p)
    out = {}
    for th_name, th in (("gamma_2", ld.gamma[2]), ("gamma_4", ld.gamma[4])):
        for e in range(1, 6):
            x = th * ld.gamma[e]
            n = scalar_exponent(ld, x)
            out[(th_name, e)] = {
                "scalar": n is not None and n.denominator == 1,
                "alpha_exponent": n,
                "equals_1": x == cyc.one,
                "equals_-alphaG": x == -ld.alpha * Gp,
            }
    return out


def generalized_C(ld: LocalData, eps: int, eps_s: int, t: int, k: int, jp: int):
    """C^{(eps)}(t, k, j') = sum_{d mod p^k} chi^{eps_s k}(d) g_{chi^{eps t}}(p^t, (p^j' - p^t d)/p^k)."""
    prime, cyc, G = ld.prime, ld.cyc, ld.G
    pj = pi_pow(prime, jp)
    if k == 0:
        return cyc.one if t == 0 else gauss_power(prime, G, t, eps * t, pj, cyc)
    pk, pt = pi_pow(prime, k), pi_pow(prime, t)
    total = cyc.zero
    for d in Residues(pk):
        diff = osub(pj, omul(pt, d))
        if not odivides(pk, diff):
            continue
        kk = chi_power(prime, d, eps_s * k)
        if kk is None:
            continue
        val = cyc.one if t == 0 else gauss_power(prime, G, t, eps * t, odiv(diff, pk), cyc)
        total = total + cyc.zeta6(kk) * val
    return total


def probe_series(ld: LocalData, eps: int, j: int, rho_k: int, box: Box, theta="gamma_2",
                 angular=True, gcorr=True, rcorr=True):
    """The single-prime series of a cubic-theta probe with twist chi^eps (eps_s = eps).

    Raw coefficient: theta(p)^e0 [conj(alpha)^t] eta^t [conj(G(p^t))] R(p^t, p^k)
    rho^{eps(k - t)} C^{(eps)}(t, k, j + 6m) Q^{-e0/2 - l}.  With eps = 1 and both
    normalizations this is the paper's (local-P) (checked by `raw_vs_series`).
    """
    cyc = ld.cyc
    th = ld.gamma[2] if theta == "gamma_2" else ld.gamma[4]
    out = {}
    for (t, k, m) in box.keys():
        if t % 3 == 2:
            continue
        e0 = t % 3
        l = (t - e0) // 3
        C = generalized_C(ld, eps, eps, t, k, j + 6 * m)
        if C == 0:
            continue
        val = th ** e0 * ld.eta ** t * cyc.zeta6(eps * rho_k * (k - t)) * C
        if angular:
            val = val * ld.abar ** t
        if gcorr:
            pt = pi_pow(ld.prime, t)
            Gpt = cyc.zeta6(-ld.k4 * t) * four_term(pt, cyc)
            val = val * cyc.conj(Gpt)
        if rcorr:
            pt, pk, ptk = pi_pow(ld.prime, t), pi_pow(ld.prime, k), pi_pow(ld.prime, t + k)
            val = val * four_term(ptk, cyc) / (four_term(pt, cyc) * four_term(pk, cyc))
        val = val / (ld.sq ** e0 * ld.Q ** l)
        if val != 0:
            out[(t, k, m)] = val
    return out


def probe_S1_S2(prime: FPrime, box: Box = Box(4, 1, 1)) -> dict:
    """S1 and S2 at one prime: the X^1 (D-term) coefficient of the u = 1 row, exactly.

    For the paper's probe the X^1 coefficient is -eta(p) rho^-1, minus the value at p of
    the Hecke character psi = eta conj(chi_.(u)): the target sits in the denominator
    (the minus sign is mu(p), from gamma_1 gamma_2 = mu alpha G).  For a twist chi^e the
    natural character is psi = eta conj(chi_.(u))^e, and the ratio r = coefficient /
    (eta rho^-e) is reported exactly: r = -1 denominator, r = +1 numerator, r containing
    alpha(p) or G(p) an extra angular or finite-ray factor, r not scalar no identity.
    """
    ld = LocalData(prime)
    cyc = ld.cyc
    Gp = cyc.zeta6(-ld.k4) * ld.gamma[3]
    out = {"alpha(p) is a root of unity": alpha_is_root_of_unity(ld)}
    for name, eps in (("paper (sextic twist)", 1), ("S1 (conjugate cubic twist)", 4),
                      ("S2 (quadratic twist)", 3)):
        for norm_name, (ang, gc) in (("paper row normalization", (True, True)),
                                     ("bare row", (False, False))):
            rec = {}
            for rho_k in (0, 1):
                S = probe_series(ld, eps, 0, rho_k, box, angular=ang, gcorr=gc, rcorr=ang)
                d1 = S.get((1, 0, 0), cyc.zero)
                r = d1 / (ld.eta * cyc.zeta6(-eps * rho_k))
                n = scalar_exponent(ld, r)
                rec[rho_k] = {
                    "r": cyc.number(r),
                    "r = -1": r == -cyc.one,
                    "r = +1": r == cyc.one,
                    "r = conj(alpha G)": r == ld.abar * cyc.conj(Gp),
                    "r = -alpha G": r == -ld.alpha * Gp,
                    "alpha exponent of r": n,
                    "scalar": n is not None and n.denominator == 1,
                }
            out[(name, norm_name)] = rec
    return out


def s1_two_prime_product(p: FPrime, q: FPrime) -> bool:
    """gamma_2(pq) gamma_4(pq) = 1 exactly: the S1 product carries no mu and no cross phase."""
    cyc = _field_for_moduli([12 * p.ell, 12 * q.ell])
    g2 = gauss_index([p, q], 2, cyc)
    g4 = gauss_index([p, q], 4, cyc)
    return g2 * g4 == onorm(omul(p.pi, q.pi)) * cyc.one


def s1_pair_phase(p: FPrime, q: FPrime, insert_G: bool = True) -> dict:
    """S1 and the paper's probe at c = p, q and pq, in the paper's row normalization, exactly.

    `insert_G=False` drops the conj(G(c)) insertion, a lesion that must flip both
    separation verdicts wherever R(p, q) != 1.

    The squarefree part of the u-row coefficient, that is the factors that are not
    characters of A (eta, Xi, xi(A), chi_A(b_*) and chi_c(u) are, and cancel in the ratio):
    X_e(c) = gamma_2(c) gamma_e(c) conj(alpha(c)) conj(G(c)), with e = 1 for the paper's
    sextic twist and e = 4 for S1.  By Equation (4.7) X_1(c) = mu(c), which separates.
    For S1, gamma_2 gamma_4 = 1 leaves X_4(c) = conj(alpha(c) G(c)), and G(pq) = G(p) G(q)
    R(p, q), so X_4(pq) = conj(R(p, q)) X_4(p) X_4(q).  Gamma(c) = S_Gamma(c)/|c| is
    summed directly (no four-term formula) and R(p, q) = Gamma(pq)/(Gamma(p) Gamma(q)).
    """
    cyc = _field_for_moduli([12 * p.ell, 12 * q.ell])
    parts = {}
    for name, primes in (("p", [p]), ("q", [q]), ("pq", [p, q])):
        c = ONE
        for pr in primes:
            c = omul(c, pr.pi)
        qc = onorm(c)
        sq = sqrt_int(cyc, qc)
        g2 = gauss_index(primes, 2, cyc)
        gam = quad_sum(c, cyc) / sq                         # Gamma(c)
        k4 = chi_index_power(primes, (4, 0), 1)
        Gc = cyc.zeta6(-k4) * gam                           # G(c) = conj(chi_c(4)) Gamma(c)
        abar_c = cyc.conj(cyc.from_O(c) / sq)
        corr = cyc.conj(Gc) if insert_G else cyc.one
        X = {e: g2 * gauss_index(primes, e, cyc) / qc * abar_c * corr for e in (1, 4)}
        parts[name] = {"X": X, "Gamma": gam, "c": c,
                       "gamma_2 gamma_4 = 1": g2 * gauss_index(primes, 4, cyc) == qc * cyc.one}
    R = parts["pq"]["Gamma"] / (parts["p"]["Gamma"] * parts["q"]["Gamma"])
    R4 = four_term(parts["pq"]["c"], cyc) / (four_term(parts["p"]["c"], cyc) * four_term(parts["q"]["c"], cyc))
    X1 = {k: v["X"][1] for k, v in parts.items()}
    X4 = {k: v["X"][4] for k, v in parts.items()}
    return {
        "R(p,q)": cyc.number(R),
        "R = -1": R == -cyc.one,
        "R = +1": R == cyc.one,
        "R agrees with the four-term formula": R == R4,
        "gamma_2 gamma_4 = 1 at p, q, pq": all(v["gamma_2 gamma_4 = 1"] for v in parts.values()),
        "paper's probe: X_1 = mu at p, q, pq": (X1["p"] == -cyc.one and X1["q"] == -cyc.one
                                               and X1["pq"] == cyc.one),
        "paper's probe separates": X1["pq"] == X1["p"] * X1["q"],
        "S1 separates": X4["pq"] == X4["p"] * X4["q"],
        "S1: X_4(pq) = conj(R) X_4(p) X_4(q)": X4["pq"] == cyc.conj(R) * X4["p"] * X4["q"],
    }


# --- S3: the classical theta over Q(i) with the quartic twist ------------------------
#
# Z[i] arithmetic on pairs (a, b) = a + b i; the quartic symbol by PARI's nfmodpr on
# nfinit(y^2+1); the self-dual character e_K(z) = exp(2 pi i Tr(z/2)) = exp(2 pi i Re z).
# The classical theta sum_{x in Z[i]} e(x^2 z) has its coefficient at A equal to
# #{x : x^2 = A}, which vanishes at every A = p (a prime is not a square).

NF_I = pari.nfinit("y^2+1")
UNITS4 = [(1, 0), (0, 1), (-1, 0), (0, -1)]  # i^k


def imul(x, y):
    return (x[0] * y[0] - x[1] * y[1], x[0] * y[1] + x[1] * y[0])


def iconj(x):
    return (x[0], -x[1])


def inorm(x):
    return x[0] * x[0] + x[1] * x[1]


def ipow(x, n):
    r = (1, 0)
    for _ in range(n):
        r = imul(r, x)
    return r


def idivides(m, x):
    n = inorm(m)
    w = imul(x, iconj(m))
    return w[0] % n == 0 and w[1] % n == 0


def idiv(x, m):
    n = inorm(m)
    w = imul(x, iconj(m))
    assert w[0] % n == 0 and w[1] % n == 0
    return (w[0] // n, w[1] // n)


def iresidues(m):
    h = pari.idealhnf(NF_I, pari(f"[{m[0]},{m[1]}]~"))
    h11, h22 = int(h[0, 0]), int(h[1, 1])
    assert h11 * h22 == inorm(m)
    return [(a, b) for b in range(h22) for a in range(h11)]


def iechar(v, m) -> Fraction:
    """Exponent of e_K(v/m) = exp(2 pi i Re(v/m))."""
    return Fraction(imul(v, iconj(m))[0], inorm(m)) % 1


class IPrime:
    """A split prime of Z[i] (norm ell = 1 mod 4) with primary generator (= 1 mod 2+2i)."""

    def __init__(self, ell: int):
        assert ell % 4 == 1
        gens = []
        bound = math.isqrt(ell) + 1
        for a in range(-bound, bound + 1):
            for b in range(-bound, bound + 1):
                if a * a + b * b == ell and idivides((2, 2), (a - 1, b)):
                    gens.append((a, b))
        gens.sort(key=lambda g: -g[1])
        assert len(gens) == 2
        self.pi = gens[0]
        self.ell = self.Q = ell
        pr = [d for d in pari.idealprimedec(NF_I, ell)
              if int(pari.nfeltval(NF_I, pari(f"[{self.pi[0]},{self.pi[1]}]~"), d)) == 1]
        self.modpr = pari.nfmodprinit(NF_I, pr[0])
        self.unit_images = [pari.nfmodpr(NF_I, pari(f"[{u[0]},{u[1]}]~"), self.modpr) for u in UNITS4]
        self._sym = {}

    def sym(self, x):
        """Exponent k with the quartic symbol (x/p)_4 = i^k, or None when p | x."""
        key = (x[0] % self.ell, x[1] % self.ell)
        if key not in self._sym:
            r = pari.nfmodpr(NF_I, pari(f"[{key[0]},{key[1]}]~"), self.modpr)
            if r == 0:
                self._sym[key] = None
            else:
                s = r ** ((self.Q - 1) // 4)
                ks = [k for k, u in enumerate(self.unit_images) if s == u]
                assert len(ks) == 1
                self._sym[key] = ks[0]
        return self._sym[key]

    def valuation(self, x):
        v = 0
        while idivides(self.pi, x):
            x = idiv(x, self.pi)
            v += 1
        return v


def s3_gauss(ip: IPrime, t: int, r: int, y, cyc: Cyc):
    """g_{chi^r}(p^t, y) over Z[i] by direct summation (quartic symbol, 4 | r is the indicator)."""
    m = ipow(ip.pi, t)
    counts = {}
    for d in iresidues(m):
        k = ip.sym(d)
        if k is None:
            continue
        e = (k * r % 4) * (cyc.N // 4) + cyc.exp_of(iechar(imul(y, d), m))
        counts[e] = counts.get(e, 0) + 1
    return cyc.from_counts(counts)


def probe_S3(ell: int = 13) -> dict:
    """S3 at one prime of Z[i]: which local coefficients can exist, and whether they are scalar."""
    ip = IPrime(ell)
    cyc = Cyc(4 * ell)
    big = Cyc(4 * ell ** 2)
    Q = ip.Q
    G = {r: s3_gauss(ip, 1, r, (1, 0), cyc) for r in range(4)}
    sq = sqrt_int(cyc, Q)
    alpha = (ip.pi[0] + ip.pi[1] * cyc.i()) / sq
    out = {"prime": f"split prime of Z[i] of norm {Q}, pi = {ip.pi[0]}{ip.pi[1]:+d}i"}
    # theta coefficients #{x : x^2 = p^t}, by direct enumeration of x with N(x) = Q^t
    theta = {}
    for t in range(5):
        target = ipow(ip.pi, t)
        n = 0
        if t % 2 == 0:
            half = Q ** (t // 2)
            for a in range(-math.isqrt(half), math.isqrt(half) + 1):
                b2 = half - a * a
                b = math.isqrt(b2)
                for bb in ({b, -b} if b else {0}):
                    if b * b == b2 and imul((a, bb), (a, bb)) == target:
                        n += 1
        theta[t] = n
    out["theta coefficient #{x: x^2 = p^t}, t=0..4"] = theta
    out["no theta coefficient at A = p"] = theta[1] == 0 and theta[3] == 0
    # the twist's Gauss sums at A = p (quartic) and A = p^2 (quadratic, by the lift)
    out["quadratic Gauss sum scalar: G_2^2 = chi^2(-1) Q"] = (
        G[2] ** 2 == cyc.root(2 * ip.sym((-1, 0)), 4) * Q
    )

    def alpha_exp(x):
        return alpha_exponent(x, alpha, cyc, 24)

    out["alpha(p) a root of unity"] = alpha ** cyc.N == cyc.one
    out["alpha exponent of gamma_1 (quartic)"] = alpha_exp(G[1] / sq)
    out["alpha exponent of gamma_2 (quadratic)"] = alpha_exp(G[2] / sq)
    out["alpha exponent of gamma_3"] = alpha_exp(G[3] / sq)
    # the lift at t = 2 against direct summation, all r and j' <= 3
    lift = True
    for r in range(4):
        for jp in range(4):
            direct = s3_gauss(ip, 2, r, ipow(ip.pi, jp), big)
            if r % 4:
                expect = Q * G[r] if jp == 1 else cyc.zero
            else:
                expect = ((Q ** 2 if jp >= 2 else 0) - (Q if jp >= 1 else 0)) * cyc.one
            lift = lift and direct == cyc.embed(expect, big)
    out["lift at p^2 = direct summation"] = lift
    # which (t, k, j') give a nonzero C^{(4)} with the theta support t even, k <= 1:
    # t = 2 needs j' = 1 (k = 0) or j' = 2 (k = 1); t = 4 is principal (Ramanujan).
    rows = {}
    for j in range(4):
        live = []
        for t in (1, 2, 4):
            if theta[t] == 0:
                continue
            for k in (0, 1):
                for m in range(2):
                    jp = j + 4 * m
                    if t % 4:  # quadratic character at t = 2
                        ok = (k == 0 and jp == t - 1) or (k == 1 and jp == t)
                    else:      # principal: Ramanujan sum nonzero for j' >= t - 1 (k = 0)
                        ok = (k == 0 and jp >= t - 1) or (k == 1 and jp >= t)
                    if ok:
                        live.append((t, k, m))
        rows[j] = live
    out["live local monomials X^t B^k V^m by row j (fourth-power-free u)"] = rows
    out["smallest x-power in the u = 1 row"] = min((t for (t, k, m) in rows[0]), default=None)
    return out


def s3_C_direct(ip: IPrime, t: int, k: int, jp: int, cyc: Cyc):
    """C^{S3}(t, k, j') by definition, inner Gauss sums by direct summation over Z[i]/p^t."""
    pj = ipow(ip.pi, jp)
    if k == 0:
        return cyc.one if t == 0 else s3_gauss(ip, t, t, pj, cyc)
    pk, pt = ipow(ip.pi, k), ipow(ip.pi, t)
    total = cyc.zero
    for d in iresidues(pk):
        diff = (pj[0] - imul(pt, d)[0], pj[1] - imul(pt, d)[1])
        if not idivides(pk, diff):
            continue
        kk = ip.sym(d)
        if kk is None:
            continue
        kk = kk * k % 4
        val = cyc.one if t == 0 else s3_gauss(ip, t, t, idiv(diff, pk), cyc)
        total = total + cyc.root(kk, 4) * val
    return total


def probe_S3_direct(ell: int = 5, t_max: int = 4) -> dict:
    """S3 at one prime of Z[i], every local scalar by direct summation (no lift).

    The local coefficient at X^t B^k V^m in row j is theta(p^t) eta^t rho^{k-t}
    C^{S3}(t, k, j + 4m) up to normalization; theta(p^t) = #{x : x^2 = p^t}.  Reports
    the nonzero monomials for t <= t_max, k <= 1, m <= 1, and whether each is scalar
    (a nonzero rational times mu_infinity alpha^Z).
    """
    ip = IPrime(ell)
    cyc = Cyc(4 * ell ** t_max)
    Q = ip.Q
    sq = sqrt_int(cyc, Q)
    alpha = (ip.pi[0] + ip.pi[1] * cyc.i()) / sq
    theta = {t: (2 if t % 2 == 0 else 0) for t in range(t_max + 1)}

    def alpha_exp(x):
        return alpha_exponent(x, alpha, cyc, 24)

    rows = {}
    for j in range(4):
        live = {}
        for t in range(1, t_max + 1):
            for k in (0, 1):
                for m in (0, 1):
                    C = s3_C_direct(ip, t, k, j + 4 * m, cyc)
                    if C == 0:
                        continue
                    nrm = C * cyc.conj(C)
                    rat = Fraction(str(pari.lift(nrm)))
                    assert rat.denominator == 1
                    unit = C / sqrt_int(cyc, rat.numerator)
                    a = alpha_exp(unit)
                    live[(t, k, m)] = {
                        "theta(p^t)": theta[t],
                        "|C|^2": rat.numerator,
                        "alpha exponent": a,
                        "scalar": a is not None and a.denominator == 1,
                        "survives theta": theta[t] != 0,
                    }
        rows[j] = live
    return {
        "prime": f"split prime of Z[i] of norm {Q}, pi = {ip.pi[0]}{ip.pi[1]:+d}i",
        "rows": rows,
        "X^1 term possible": any(key[0] == 1 and v["survives theta"] for r in rows.values() for key, v in r.items()),
        "every surviving coefficient scalar": all(v["scalar"] for r in rows.values() for v in r.values() if v["survives theta"]),
        "some non-surviving coefficient non-scalar": any(not v["scalar"] for r in rows.values() for v in r.values() if not v["survives theta"]),
        "smallest surviving x-power, u = 1": min((key[0] for key, v in rows[0].items() if v["survives theta"]), default=None),
    }


# ---------------------------------------------------------------------------
# H. The analytic bookkeeping of Lemma 7.1 (lines 4049-4066 and 4148-4185)
# ---------------------------------------------------------------------------
#
# Symbolic, in sympy: q = sqrt(Q), X = Q^{-x}, B = Q^{-w}, V = Q^{-6z}, and unimodular
# phases.  H_p - 1 = Num / ((1 - D)(1 - R)(1 - V)) with Num a polynomial.  A monomial
# q^a X^b B^c V^d has size Q^{a/2 - b x_r - c w_r - 6 d z_r}; the denominators are
# 1 + (smaller terms) in both regions, so the largest monomial of Num bounds H_p - 1.

REGION_ONE = {"x": Fraction(51, 100), "z": Fraction(17, 50), "w": Fraction(-1, 100)}
REGION_TWO = {"x": Fraction(7, 8), "z": Fraction(33, 200), "w": Fraction(19, 20)}


def hp_defect_numerator(j: int, fault: str | None = None):
    """Num = (1-D)(1-R)(1-V)(H_p - 1) from (local-H-defect), expanded in sympy."""
    import sympy as sp
    q, X, B, V, eta, rho, abar, kb = sp.symbols("q X B V eta rho abar kb", nonzero=True)
    a = abar ** 3 * eta ** 3
    b = abar ** 2 * eta ** 2 * kb
    R = a ** 2 * q ** 8 * X ** 6 * V
    if j == 0:
        W = rho * B
        D = (eta * rho if fault == "D_unconjugated" else eta / rho) * X
    else:
        W = sp.Integer(0)
        D = sp.Integer(0)
    J = {
        0: -eta / rho * X + rho * B * R,
        1: eta * X * B,
        2: a / rho ** 3 * q ** 3 * X ** 3,
        3: -eta * b / rho ** 2 * q ** 4 * X ** 3 * B + b ** 2 / rho ** 4 * q ** 4 * X ** 4,
        4: -eta * a / rho ** 3 * q ** 5 * X ** 4 * B,
        5: -a ** 2 * q ** 6 * X ** 6,
    }[j]
    delta = 1 if j <= 1 else 0
    inner = R * (1 - q ** -2) - eta * (q ** 2 - 1) * X * B * V ** delta + J * (1 - V) + D * (1 - R) * (1 - V)
    num = (1 - R) * (1 - V) * (D * (V + W - V * W) - V * W) + (1 - V) * (1 - W) * inner
    return sp.expand(num), (q, X, B, V)


def monomial_exponents(j: int, fault: str | None = None):
    """The (a, b, c, d) of every monomial q^a X^b B^c V^d of Num with nonzero coefficient."""
    import sympy as sp
    num, (q, X, B, V) = hp_defect_numerator(j, fault)
    out = set()
    for term in sp.Add.make_args(num):
        powers = term.as_powers_dict()
        out.add((int(powers.get(q, 0)), int(powers.get(X, 0)), int(powers.get(B, 0)), int(powers.get(V, 0))))
    return sorted(out)


def size_exponent(mono, x, w, z) -> Fraction:
    a, b, c, d = mono
    return Fraction(a, 2) - b * x - c * w - 6 * d * z


def region_max(j: int, region: str, eps0: Fraction = Fraction(1, 1000), fault=None):
    """The largest size exponent of Num over the region, with the monomial attaining it.

    Region one is x_r >= 51/100, z_r >= 17/50, w_r >= -1/100, x_r + w_r >= 1 + eps0
    (eq:local-region-one): exponents are linear and decreasing in x, w, z, so the
    maximum sits at the corners (51/100, 49/100 + eps0) and (101/100 + eps0, -1/100).
    Region two (eq:local-region-two) has the single corner (7/8, 19/20, 33/200).
    """
    monos = monomial_exponents(j, fault)
    if region == "two":
        corners = [(REGION_TWO["x"], REGION_TWO["w"], REGION_TWO["z"])]
    else:
        z = REGION_ONE["z"]
        corners = [(REGION_ONE["x"], 1 + eps0 - REGION_ONE["x"], z),
                   (1 + eps0 - REGION_ONE["w"], REGION_ONE["w"], z)]
    best = None
    for mono in monos:
        if mono == (0, 0, 0, 0):
            raise AssertionError("Num has a constant term: H_p - 1 does not vanish at X = B = V = 0")
        e = max(size_exponent(mono, *c) for c in corners)
        if best is None or e > best[0]:
            best = (e, mono)
    return best


def analytic_claims(eps0: Fraction = Fraction(1, 1000), fault=None) -> dict:
    """Lemma 7.1's stated bounds, row by row (j = 0: p does not divide u; j >= 1: p | u)."""
    eps_h = min(eps0, Fraction(1, 50))
    out = {}
    for j in range(6):
        e1, m1 = region_max(j, "one", eps0, fault)
        e2, m2 = region_max(j, "two", eps0, fault)
        if j == 0:
            out[j] = {
                "region one max": e1, "region one claim": -1 - eps_h, "region one ok": e1 <= -1 - eps_h,
                "region two max": e2, "region two claim": Fraction(-363, 200), "region two ok": e2 <= Fraction(-363, 200),
                "region two closest": m2,
            }
        else:
            out[j] = {
                "region one max": e1, "region one claim": -eps_h, "region one ok": e1 <= -eps_h,
                "region two max": e2, "region two claim": Fraction(-33, 40), "region two ok": e2 <= Fraction(-33, 40),
                "region two closest": m2,
            }
    # u = 1 tail above P_0: sum over ideals of norm > P_0 of Q^{-363/200} is O(P_0^{1-363/200})
    out["tail exponent 1 - 363/200"] = Fraction(1) - Fraction(363, 200)
    out["tail implies c_H = 4/5"] = Fraction(1) - Fraction(363, 200) <= Fraction(-4, 5)
    return out


def s1_factorization(prime: FPrime, box: Box = Box(7, 2, 3)) -> dict:
    """The S1 local factor at u = 1 with a bare row, against an explicit scalar shape.

    Bare row: theta = gamma_2, twist chi^4 everywhere, no angular or G insertion, and no
    R insertion (the chi^4 reciprocity phase is R^4 = 1).  With psi = eta (u = 1) the
    candidate is P = (1-V)^-1 (1-W)^-1 [(1 - psi^2 X^2)/(1 - psi X)] H, that is
    L(x, psi)/L(2x, psi^2) at this prime.  Returns the monomials of H - 1 in the box
    with their size exponents in region two (x, w, z) = (7/8, 19/20, 33/200) and in
    region one's corner (51/100, 49/100 + 1/1000, 17/50).
    """
    ld = LocalData(prime)
    cyc = ld.cyc
    S = probe_series(ld, 4, 0, 0, box, angular=False, gcorr=False, rcorr=False)
    psi = S.get((1, 0, 0), cyc.zero)
    one = pconst(cyc.one)
    V = {(0, 0, 1): cyc.one}
    W = {(0, 1, 0): cyc.one}
    lin = padd(one, {(1, 0, 0): -psi}, cyc)                   # 1 - psi X
    inv_quad = dict(one)                                       # (1 - psi^2 X^2)^{-1}
    pw = dict(one)
    for _ in range(box.T):
        pw = pmul(pw, {(2, 0, 0): psi * psi}, cyc, box)
        inv_quad = padd(inv_quad, pw, cyc)
    H = pmul(pmul(pmul(pmul(S, padd(one, pscale(V, -cyc.one), cyc), cyc, box),
                       padd(one, pscale(W, -cyc.one), cyc), cyc, box), lin, cyc, box), inv_quad, cyc, box)
    Hm1 = padd(H, pscale(one, -cyc.one), cyc)
    Q = ld.Q
    rows = {}
    worst = {"two": None, "one": None}
    corners = {"two": [(0.875, 0.95, 0.165)], "one": [(0.51, 0.491, 0.34), (1.011, -0.01, 0.34)]}
    for (t, k, m), v in sorted(Hm1.items()):
        size = math.log(abs(cyc.number(v)), Q)   # |coefficient| as a power of Q, at this prime
        rows[(t, k, m)] = round(size, 6)
        for reg, cs in corners.items():
            e = max(size - t * x - k * w - 6 * m * z for (x, w, z) in cs)
            if worst[reg] is None or e > worst[reg][0]:
                worst[reg] = (round(e, 6), (t, k, m))
    return {
        "psi = X^1 coefficient": cyc.number(psi),
        "psi = +eta": psi == ld.eta,
        "H - 1 monomials (t,k,m) -> log_Q|coefficient|": rows,
        "pure X and X^2 absent from H - 1": (1, 0, 0) not in Hm1 and (2, 0, 0) not in Hm1,
        "largest size exponent of H - 1, region two (measured at this prime)": worst["two"],
        "largest size exponent of H - 1, region one corners (measured at this prime)": worst["one"],
    }


