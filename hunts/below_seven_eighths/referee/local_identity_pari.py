_POW_CACHE: dict = {}


def pi_pow(prime: FPrime, n: int):
    key = (prime.ell, prime.pi, n)
    if key not in _POW_CACHE:
        _POW_CACHE[key] = opow(prime.pi, n)
    return _POW_CACHE[key]


def gauss_power_direct(prime: FPrime, t: int, r: int, y, cyc: Cyc):
    """g_{chi_p^r}(p^t, y) by direct summation over O/p^t (any r; 6 | r is the indicator)."""
    m = pi_pow(prime, t)
    counts = {}
    for d in Residues(m):
        k = chi_power(prime, d, r)
        if k is None:
            continue
        e = cyc.sextic(k) + cyc.exp_of(echar(omul(y, d), m))
        counts[e] = counts.get(e, 0) + 1
    return cyc.from_counts(counts)


def lift_value(prime: FPrime, G, t: int, r: int, jp: int, cyc: Cyc):
    """The paper's lift (lines 3877-3883): g_{chi_p^r}(p^t, p^{j'}) for t >= 1.

    `Q^{t-1} G_r 1_{j'=t-1}` when 6 does not divide r, and the Ramanujan sum
    `Q^t 1_{j'>=t} - Q^{t-1} 1_{j'>=t-1}` when it does.
    """
    Q = prime.Q
    if t == 0:
        return cyc.one
    if r % 6:
        return Q ** (t - 1) * G[r % 6] if jp == t - 1 else cyc.zero
    return ((Q ** t if jp >= t else 0) - (Q ** (t - 1) if jp >= t - 1 else 0)) * cyc.one


def gauss_power(prime: FPrime, G, t: int, r: int, y, cyc: Cyc):
    """g_{chi_p^r}(p^t, y) for any y in O from the lift and the unit substitution d -> d/h.

    The substitution is elementary (y = p^v h with h a p-unit gives the factor
    conj(chi_p(h))^r); the lift itself is checked against direct summation by
    `lift_checks`.
    """
    if t == 0:
        return cyc.one
    Q = prime.Q
    if y == (0, 0):
        return (Q ** t - Q ** (t - 1)) * cyc.one if r % 6 == 0 else cyc.zero
    v = prime.valuation(y)
    if v >= t:
        return (Q ** t - Q ** (t - 1)) * cyc.one if r % 6 == 0 else cyc.zero
    val = lift_value(prime, G, t, r, v, cyc)
    if r % 6 == 0:
        return val
    h = odiv(y, pi_pow(prime, v))
    k = chi_power(prime, h, r)
    return cyc.zeta6(-k) * val


def C_p(prime: FPrime, G, t: int, k: int, jp: int, cyc: Cyc, inner=None):
    """C_p(t, k, j') from its definition (local-scalar-definition, lines 3892-3897).

    The sum over d mod p^k is done term by term, congruence included; the inner Gauss
    sum is `gauss_power` (or `inner`, e.g. direct summation, when given).
    """
    inner = inner or (lambda tt, rr, yy: gauss_power(prime, G, tt, rr, yy, cyc))
    pj = pi_pow(prime, jp)
    if k == 0:
        return cyc.one if t == 0 else inner(t, t, pj)
    pk = pi_pow(prime, k)
    pt = pi_pow(prime, t)
    total = cyc.zero
    for d in Residues(pk):
        diff = osub(pj, omul(pt, d))
        if not odivides(pk, diff):
            continue
        kk = chi_power(prime, d, k)
        if kk is None:
            continue
        val = cyc.one if t == 0 else inner(t, t, odiv(diff, pk))
        total = total + cyc.zeta6(kk) * val
    return total


def C_p_table(prime: FPrime, G, t: int, k: int, jp: int, cyc: Cyc):
    """The paper's claimed evaluation (local-scalar-values, lines 3901-3909)."""
    if t == 0 and k == 0:
        return cyc.one
    if t == 0:
        return cyc.one if jp == 0 else cyc.zero
    if k == 0:
        return lift_value(prime, G, t, t, jp, cyc)
    if k == 1 and jp >= 1:
        return prime.omega_p() * G[1] * lift_value(prime, G, t, t - 1, jp - 1, cyc)
    return cyc.zero


def lift_checks(prime: FPrime, t_max: int, jp_max: int | None = None) -> dict:
    """The lift (lines 3877-3883) against direct summation over O/p^t, t <= t_max, all r.

    Direct sums live in Q(zeta_{6 ell^t}); the lift's value is embedded there.
    """
    small = prime.small_field()
    G = gauss_sums(prime, small)
    out = {}
    for t in range(1, t_max + 1):
        big = Cyc(math.lcm(small.N, prime.ell ** t * 6))
        for r in range(6):
            for jp in range(0, (jp_max if jp_max is not None else t + 1) + 1):
                direct = gauss_power_direct(prime, t, r, pi_pow(prime, jp), big)
                lifted = small.embed(lift_value(prime, G, t, r, jp, small), big)
                out[(t, r, jp)] = direct == lifted
    return out


def scalar_table_checks(prime: FPrime, t_max: int, k_max: int, jp_max: int, G=None,
                        direct_t_max: int = 0) -> dict:
    """C_p by definition against the paper's table, all (t, k, j') in the box.

    With `direct_t_max > 0` the inner Gauss sums for t <= direct_t_max are summed
    directly over O/p^t instead of through the lift.
    """
    small = prime.small_field()
    G = G or gauss_sums(prime, small)
    out = {}
    for t in range(t_max + 1):
        if 0 < t <= direct_t_max:
            big = Cyc(math.lcm(small.N, prime.ell ** t * 6))
            inner = (lambda tt, rr, yy, big=big: gauss_power_direct(prime, tt, rr, yy, big))
            cyc_used = big
            Gu = {r: small.embed(G[r], big) for r in G}
        else:
            inner = None
            cyc_used = small
            Gu = G
        for k in range(k_max + 1):
            for jp in range(jp_max + 1):
                by_def = C_p(prime, Gu, t, k, jp, cyc_used, inner=inner)
                claimed = C_p_table(prime, Gu, t, k, jp, cyc_used)
                out[(t, k, jp)] = by_def == claimed
    return out


