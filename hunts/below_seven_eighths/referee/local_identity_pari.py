def _field_for_moduli(ells, extra=12):
    n = extra
    for e in ells:
        n = math.lcm(n, e)
    return Cyc(n)


def chi_index_power(primes, x, r):
    """Exponent of chi_c(x)^r for c = prod of the given primes (with multiplicity), or None."""
    total = 0
    for p in primes:
        k = chi_power(p, x, r)
        if k is None:
            return None
        total += k
    return total % 6


def gauss_index(primes, j, cyc, y=ONE):
    """g_j(c, y) = sum_{v mod c} chi_c(v)^j e(y v/c), c = product of the primary generators."""
    c = ONE
    for p in primes:
        c = omul(c, p.pi)
    counts = {}
    for v in Residues(c):
        k = chi_index_power(primes, v, j)
        if k is None:
            continue
        f = echar(omul(y, v), c)
        e = cyc.sextic(k) + cyc.exp_of(f)
        counts[e] = counts.get(e, 0) + 1
    return cyc.from_counts(counts)


def quad_sum(c, cyc):
    """S_Gamma(c) = sum_{x mod c} e(x^2/c), so Gamma(c) = S_Gamma(c)/|c| (line 844)."""
    counts = {}
    for x in Residues(c):
        f = echar(omul(x, x), c)
        e = cyc.exp_of(f)
        counts[e] = counts.get(e, 0) + 1
    return cyc.from_counts(counts)


def four_term(c, cyc):
    """Lemma 4.3's value of Gamma(c) for odd c = a + b omega: (1 + i^-b + i^a + i^(b-a))/2."""
    a, b = c
    i = cyc.i()
    return (1 + i ** ((-b) % 4) + i ** (a % 4) + i ** ((b - a) % 4)) / 2


def equation_4_7_checks(primes) -> dict:
    """Equation (4.7) (lines 964-969) at the squarefree index c = prod(primes), exactly.

    Cleared of square roots (q = q_c, g_j unnormalized, S_Gamma = sum e(x^2/c)):
    gamma_2^3 = mu alpha            <=>  g_2^3 = mu c q,
    gamma_1 gamma_2 = mu alpha G    <=>  g_1 g_2 = mu c conj(chi_c(4)) S_Gamma,
    G = conj(chi_c(4)) gamma_3      <=>  S_Gamma = g_3,
    |G| = 1                         <=>  S_Gamma conj(S_Gamma) = q.
    """
    assert len({(p.ell, p.pi) for p in primes}) == len(primes), "c must be squarefree"
    cyc = _field_for_moduli([12 * p.ell for p in primes])
    c = ONE
    for p in primes:
        c = omul(c, p.pi)
    assert is_primary(c)
    q = onorm(c)
    mu = (-1) ** len(primes)
    g = {j: gauss_index(primes, j, cyc) for j in (1, 2, 3)}
    sg = quad_sum(c, cyc)
    k4 = chi_index_power(primes, (4, 0), 1)
    cc = cyc.from_O(c)
    return {
        "gamma_2(c)^3 = mu(c) alpha(c)": g[2] ** 3 == mu * q * cc,
        "gamma_1(c) gamma_2(c) = mu(c) alpha(c) G(c)": g[1] * g[2] == mu * cc * cyc.zeta6(-k4) * sg,
        "G(c) = conj(chi_c(4)) gamma_3(c)  [Gamma(c) = gamma_3(c)]": sg == g[3],
        "|G(c)| = 1": sg * cyc.conj(sg) == q * cyc.one,
        "Gamma(c) four-term formula (Lemma 4.3)": sg == sqrt_int(cyc, q) * four_term(c, cyc),
    }


