# --- arithmetic in O = Z[omega], exact integers ------------------------------

def omul(x, y):
    a, b = x
    c, d = y
    return (a * c - b * d, a * d + b * c - b * d)


def oadd(x, y):
    return (x[0] + y[0], x[1] + y[1])


def osub(x, y):
    return (x[0] - y[0], x[1] - y[1])


def oneg(x):
    return (-x[0], -x[1])


def oconj(x):
    a, b = x
    return (a - b, -b)


def onorm(x):
    a, b = x
    return a * a - a * b + b * b


def otrace(x):
    return 2 * x[0] - x[1]


def opow(x, n):
    r = ONE
    for _ in range(n):
        r = omul(r, x)
    return r


def oscale(x, k):
    return (x[0] * k, x[1] * k)


def odivides(m, x):
    """True when `m | x` in O."""
    n = onorm(m)
    w = omul(x, oconj(m))
    return w[0] % n == 0 and w[1] % n == 0


def odiv(x, m):
    """Exact quotient `x / m` in O (asserted)."""
    n = onorm(m)
    w = omul(x, oconj(m))
    if w[0] % n or w[1] % n:
        raise ArithmeticError(f"{m} does not divide {x}")
    return (w[0] // n, w[1] // n)


def is_primary(x) -> bool:
    return x[0] % 3 == 1 and x[1] % 3 == 0


def pari_elt(x):
    return pari(f"[{x[0]},{x[1]}]~")


class Residues:
    """A complete residue system of O modulo the ideal generated by `m`.

    PARI's `idealhnf` gives an upper triangular basis `[h11, h12; 0, h22]` of the
    ideal in the integral basis `(1, omega)`; the pairs `0 <= a < h11`,
    `0 <= b < h22` are then a complete residue system.
    """

    def __init__(self, m):
        self.m = m
        if m == ONE or onorm(m) == 1:
            self.h11, self.h12, self.h22 = 1, 0, 1
        else:
            h = pari.idealhnf(NF, pari_elt(m))
            self.h11, self.h12, self.h22 = int(h[0, 0]), int(h[0, 1]), int(h[1, 1])
        assert self.h11 * self.h22 == onorm(m)

    def __iter__(self):
        for b in range(self.h22):
            for a in range(self.h11):
                yield (a, b)

    def __len__(self):
        return self.h11 * self.h22

    def reduce(self, x):
        q = x[1] // self.h22
        b = x[1] - q * self.h22
        a = (x[0] - q * self.h12) % self.h11
        return (a, b)


def echar(v, m) -> Fraction:
    """The exponent of `e(v/m)`: the fraction `Tr(v/(m lambda)) mod 1`."""
    ml = omul(m, LAMBDA)
    return Fraction(otrace(omul(v, oconj(ml))), onorm(ml)) % 1


# --- cyclotomic fields --------------------------------------------------------

class Cyc:
    """The cyclotomic field `Q(zeta_N)`, elements as PARI polmods mod `polcyclo(N)`.

    The embedding used for signs is `z -> exp(2 pi i / N)`, so `omega = z^(N/3)` is
    `e^{2 pi i/3}` as in the paper.  Elements of different fields are never mixed:
    `embed` moves an element up explicitly.
    """

    _cache: dict[int, "Cyc"] = {}

    def __new__(cls, n: int):
        if n not in cls._cache:
            obj = super().__new__(cls)
            obj.N = n
            obj.Phi = pari.polcyclo(n, ZV)
            obj.one = pari.Mod(1, obj.Phi)
            obj.zero = pari.Mod(0, obj.Phi)
            obj.degree = int(pari.poldegree(obj.Phi))
            cls._cache[n] = obj
        return cls._cache[n]

    def root(self, num, den):
        """zeta_den^num."""
        if self.N % den:
            raise ValueError(f"zeta_{den} is not in Q(zeta_{self.N})")
        e = (num * (self.N // den)) % self.N
        return pari.Mod(ZV ** e, self.Phi)

    def rootf(self, frac: Fraction):
        """exp(2 pi i frac) for a rational frac with denominator dividing N."""
        return self.root(frac.numerator, frac.denominator)

    def sextic(self, k: int) -> int:
        """The exponent e with zeta_6^k = zeta_N^e (requires 6 | N)."""
        if self.N % 6:
            raise ValueError(f"6 does not divide N = {self.N}")
        return (k * (self.N // 6)) % self.N

    def exp_of(self, frac: Fraction) -> int:
        """The exponent e with exp(2 pi i frac) = zeta_N^e (denominator must divide N)."""
        if self.N % frac.denominator:
            raise ValueError(f"denominator {frac.denominator} does not divide N = {self.N}")
        return frac.numerator * (self.N // frac.denominator)

    def from_counts(self, counts):
        """sum_e counts[e] * zeta_N^e."""
        coeffs = [0] * self.N
        for e, c in counts.items():
            coeffs[e % self.N] += c
        return pari.Mod(pari.Pol(coeffs[::-1], ZV), self.Phi)

    def coefficients(self, x) -> list:
        """Coefficients c_0, c_1, ... (PARI rationals) of the reduced representative of x."""
        lx = pari.lift(x)
        if str(pari.type(lx)) == "t_POL":
            return list(pari.Vecrev(lx))
        return [lx]

    def _from_dense(self, dense: dict, field: "Cyc"):
        coeffs = [0] * field.N
        for e, c in dense.items():
            coeffs[e % field.N] = coeffs[e % field.N] + c
        return pari.Mod(pari.Pol(coeffs[::-1], ZV), field.Phi)

    def conj(self, x):
        """Complex conjugation z -> z^{-1}, by permuting exponents (no large substitution)."""
        cs = self.coefficients(x)
        return self._from_dense({(-e) % self.N: c for e, c in enumerate(cs) if c != 0}, self)

    def embed(self, x, other: "Cyc"):
        if other.N % self.N:
            raise ValueError(f"Q(zeta_{self.N}) is not inside Q(zeta_{other.N})")
        step = other.N // self.N
        cs = self.coefficients(x)
        return self._from_dense({e * step: c for e, c in enumerate(cs) if c != 0}, other)

    def number(self, x) -> complex:
        val = pari.subst(pari.lift(x), ZV, pari(f"exp(2*Pi*I/{self.N})"))
        return complex(val)

    def owns(self, x) -> bool:
        return x.mod() == self.Phi

    def omega(self):
        return self.root(1, 3)

    def zeta6(self, k):
        return self.root(k, 6)

    def i(self):
        return self.root(1, 4)

    def from_O(self, x):
        return x[0] * self.one + x[1] * self.omega()


def sqrt_int(cyc: Cyc, n: int):
    """The positive square root of a positive integer `n` in `cyc`, exactly.

    Built from quadratic Gauss sums of the odd primes dividing the squarefree part of
    `n` (and `i` when needed); the sign is fixed by the complex embedding.
    """
    root = cyc.one
    m = n
    for p in _prime_factors(n):
        k = 0
        while m % p == 0:
            m //= p
            k += 1
        root = root * (p ** (k // 2))
        if k % 2:
            if p == 2:
                # sqrt(2) = zeta_8 + zeta_8^{-1}
                s = cyc.root(1, 8) + cyc.root(-1, 8)
            elif p == 3:
                # sqrt(3) = -i * sqrt(-3) = -i * (1 + 2 omega)
                s = -cyc.i() * (1 + 2 * cyc.omega())
            else:
                g = cyc.zero
                for a in range(1, p):
                    g = g + pari.kronecker(a, p) * cyc.root(a, p)
                s = g if p % 4 == 1 else -cyc.i() * g
            if cyc.number(s).real < 0:
                s = -s
            root = root * s
    assert root * root == n * cyc.one
    assert cyc.number(root).real > 0 and abs(cyc.number(root).imag) < 1e-9
    return root


def _prime_factors(n: int):
    out = []
    d = 2
    while d * d <= n:
        if n % d == 0:
            out.append(d)
            while n % d == 0:
                n //= d
        d += 1
    if n > 1:
        out.append(n)
    return out


# --- primes of O outside S and their sextic symbols -------------------------------

class FPrime:
    """A prime ideal of O outside S = {primes above 6}, with its primary generator.

    `ell` is the rational prime below.  Split (`ell = 1 mod 3`): residue field F_ell,
    `which` picks the primary generator with positive omega-coefficient (0) or its
    conjugate (1).  Inert (`ell = 2 mod 3`): the generator is `-ell`, residue field
    of order ell^2.  The sextic symbol is computed by PARI: `nfmodpr` reduces to the
    residue field (a `t_FFELT`), where the `(Q-1)/6` power is matched against the
    reductions of the six units.
    """

    _cache: dict[tuple, "FPrime"] = {}

    def __new__(cls, ell: int, which: int = 0):
        key = (ell, which)
        if key in cls._cache:
            return cls._cache[key]
        obj = super().__new__(cls)
        obj._setup(ell, which)
        cls._cache[key] = obj
        return obj

    def _setup(self, ell, which):
        if ell in (2, 3):
            raise ValueError("primes above 6 lie in S (paper line 591)")
        self.ell = ell
        if ell % 3 == 1:
            self.kind = "split"
            gens = []
            bound = int(math.isqrt(4 * ell)) + 2
            for a in range(-bound, bound + 1):
                for b in range(-bound, bound + 1):
                    if a * a - a * b + b * b == ell and is_primary((a, b)):
                        gens.append((a, b))
            gens.sort(key=lambda g: -g[1])
            assert len(gens) == 2 and gens[1] == oconj(gens[0])
            self.pi = gens[which]
            self.Q = ell
        else:
            self.kind = "inert"
            if which:
                raise ValueError("an inert prime has one primary generator")
            self.pi = (-ell, 0)
            assert is_primary(self.pi)
            self.Q = ell * ell
        assert (self.Q - 1) % 6 == 0
        decs = pari.idealprimedec(NF, ell)
        pr = [d for d in decs if int(pari.nfeltval(NF, pari_elt(self.pi), d)) == 1]
        assert len(pr) == 1
        self.pr = pr[0]
        self.modpr = pari.nfmodprinit(NF, self.pr)
        self.unit_images = [pari.nfmodpr(NF, pari_elt(u), self.modpr) for u in UNITS6]
        assert len({str(u) for u in self.unit_images}) == 6
        self._sym = {}
        self.residues = Residues(self.pi)

    def __repr__(self):
        return f"FPrime(norm {self.Q}, pi = {self.pi[0]} + {self.pi[1]} omega)"

    @property
    def name(self) -> str:
        return f"{self.kind} prime of norm {self.Q}, pi = {self.pi[0]}{self.pi[1]:+d}w"

    def divides(self, x) -> bool:
        return odivides(self.pi, x)

    def sym(self, x):
        """Exponent k with chi_p(x) = zeta_6^k, or None when p | x (PARI nfmodpr)."""
        key = (x[0] % self.ell, x[1] % self.ell)
        if key not in self._sym:
            r = pari.nfmodpr(NF, pari_elt(key), self.modpr)
            if r == 0:
                self._sym[key] = None
            else:
                s = r ** ((self.Q - 1) // 6)
                ks = [k for k, u in enumerate(self.unit_images) if s == u]
                assert len(ks) == 1
                self._sym[key] = ks[0]
        return self._sym[key]

    def valuation(self, x) -> int:
        """v_p(x) for x != 0, by exact division in O."""
        if x == (0, 0):
            raise ValueError("valuation of zero")
        v = 0
        while odivides(self.pi, x):
            x = odiv(x, self.pi)
            v += 1
        return v

    def omega_p(self) -> int:
        """chi_p(-1) as the integer +1 or -1."""
        k = self.sym((-1, 0))
        assert k in (0, 3)
        return 1 if k == 0 else -1

    def small_field(self) -> Cyc:
        """Q(zeta_{6 ell}) (= Q(zeta_{3 ell}), with z of even order): holds sextic
        symbols, e(./p) and the Gauss sums."""
        return Cyc(6 * self.ell if self.kind == "split" else 30)

    def big_field(self) -> Cyc:
        """Q(zeta_{12 ell}) (split) or Q(zeta_60) (norm 25): also holds i and sqrt(Q)."""
        return Cyc(12 * self.ell if self.kind == "split" else 60)


def chi_power(prime: FPrime, x, r: int):
    """Exponent of chi_p(x)^r in Z/6, or None for the zero value (any r, even 6 | r)."""
    k = prime.sym(x)
    return None if k is None else (k * r) % 6


