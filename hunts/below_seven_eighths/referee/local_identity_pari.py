def gauss_sums(prime: FPrime, cyc: Cyc | None = None, fault: str | None = None):
    """G_r = g_{chi_p^r}(p, 1) = sum_{v mod p} chi_p(v)^r e(v/p), r = 0..5 (unnormalized).

    `fault="gauss_sign"` plants the wrong sign on G_1 (the sextic Gauss sum), the
    first planted fault of the task.
    """
    cyc = cyc or prime.small_field()
    sums = {}
    for r in range(6):
        counts = {}
        for v in prime.residues:
            k = chi_power(prime, v, r)
            if k is None:
                continue
            f = echar(v, prime.pi)
            e = cyc.sextic(k) + cyc.exp_of(f)
            counts[e] = counts.get(e, 0) + 1
        sums[r] = cyc.from_counts(counts)
    if fault == "gauss_sign":
        sums[1] = -sums[1]
    elif fault is not None:
        raise ValueError(f"unknown Gauss-sum fault {fault!r}")
    return sums


def jacobi(prime: FPrime, cyc: Cyc, ra: int, rb: int):
    """J(chi^ra, chi^rb) = sum_x chi^ra(x) chi^rb(1 - x), zero-extended (line 783)."""
    counts = {}
    for x in prime.residues:
        ka = chi_power(prime, x, ra)
        kb = chi_power(prime, osub(ONE, x), rb)
        if ka is None or kb is None:
            continue
        e = cyc.sextic(ka + kb)
        counts[e] = counts.get(e, 0) + 1
    return cyc.from_counts(counts)


def lemma_4_2_checks(prime: FPrime, fault: str | None = None) -> dict:
    """Lemma 4.2 (lines 766-775) and the identities of its proof, exactly.

    The normalized statements are cleared of square roots: with `G_r` unnormalized,
    `gamma_2^3 = -alpha(p)` is `G_2^3 = -p P`, and
    `gamma_1 gamma_2 = conj(H(4)) gamma_3 gamma_2^3` is `P G_1 G_2 = conj(H(4)) G_3 G_2^3`.
    """
    cyc = prime.small_field()
    G = gauss_sums(prime, cyc, fault=fault)
    P = prime.Q
    pi = cyc.from_O(prime.pi)
    h4 = prime.sym((4, 0))
    hbar4 = cyc.zeta6(-h4)
    hm1 = prime.sym((-1, 0))
    out = {
        "G0 = -1 (line 3874)": G[0] == -cyc.one,
        "gamma_2^3 = -alpha(p) [G_2^3 = -p P]": G[2] ** 3 == -pi * P,
        "gamma_1 gamma_2 = conj(H(4)) gamma_3 gamma_2^3": P * G[1] * G[2] == hbar4 * G[3] * G[2] ** 3,
    }
    for r in range(1, 6):
        out[f"|gamma_{r}| = 1 [G_{r} conj(G_{r}) = P]"] = G[r] * cyc.conj(G[r]) == P * cyc.one
    # identities used in the proof (lines 785-834)
    for r in range(1, 6):
        out[f"tau(H^{r}) tau(conj H^{r}) = H^{r}(-1) P"] = (
            G[r] * G[(6 - r) % 6] == cyc.zeta6(hm1 * r) * P
        )
    out["J(H, H^3) = H(4) J(H, H) (line 803)"] = (
        jacobi(prime, cyc, 1, 3) == cyc.zeta6(h4) * jacobi(prime, cyc, 1, 1)
    )
    out["J(H^2, H^2) = -p (line 833)"] = jacobi(prime, cyc, 2, 2) == -pi
    out["tau_2^3 = -p P (line 834)"] = G[2] ** 3 == -pi * P
    # facts quoted inside the proof of Lemma 7.1 (lines 3886, 4079, 4117-4121, 4124)
    wp = prime.omega_p()
    out["G_1 G_{-1} = omega_p Q (line 3886)"] = G[1] * G[5] == wp * P * cyc.one
    out["gamma_3^2 = omega_p (line 4079)"] = G[3] ** 2 == wp * P * cyc.one
    out["gamma_2 gamma_4 = 1 (line 4124)"] = G[2] * G[4] == P * cyc.one
    out["gamma_1 gamma_2 = -alpha(p) conj(chi_p(4)) gamma_3 (line 4117)"] = (
        G[1] * G[2] == -pi * hbar4 * G[3]
    )
    # gamma_4/gamma_1 = -conj(alpha)/G(p), G(p) = conj(chi_p(4)) gamma_3:
    # cleared of roots this is G_4 G_3 = -conj(p) chi_p(4) G_1.
    out["gamma_4/gamma_1 = -conj(alpha(p))/G(p) (line 4120)"] = (
        G[4] * G[3] == -cyc.from_O(oconj(prime.pi)) * cyc.zeta6(h4) * G[1]
    )
    return out


