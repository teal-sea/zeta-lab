# D. The local series (local-P, lines 3997-4006) against Lemma 7.1's closed form
# ---------------------------------------------------------------------------
#
# Monomials: X = Q^{-x}, B = Q^{-w}, V = Q^{-6z}.  The summand of (local-P) at
# (e0, l, k, m) is a constant times X^t B^k V^m with t = e0 + 3l, and t determines
# (e0, l) because t mod 3 is 0 or 1.  A truncated series is a dict (t, k, m) -> value.


class Box:
    """A truncation box t <= T, k <= K, m <= M."""

    def __init__(self, T: int, K: int, M: int):
        self.T, self.K, self.M = T, K, M

    def __contains__(self, key):
        t, k, m = key
        return 0 <= t <= self.T and 0 <= k <= self.K and 0 <= m <= self.M

    def keys(self):
        for t in range(self.T + 1):
            for k in range(self.K + 1):
                for m in range(self.M + 1):
                    yield (t, k, m)

    def __repr__(self):
        return f"Box(t<={self.T}, k<={self.K}, m<={self.M})"


def padd(p, q, cyc):
    out = dict(p)
    for key, v in q.items():
        out[key] = out.get(key, cyc.zero) + v
    return {k: v for k, v in out.items() if v != 0}


def pscale(p, c):
    return {k: c * v for k, v in p.items() if c * v != 0}


def pmul(p, q, cyc, box: Box | None = None):
    out = {}
    for (t1, k1, m1), v1 in p.items():
        for (t2, k2, m2), v2 in q.items():
            key = (t1 + t2, k1 + k2, m1 + m2)
            if box is not None and key not in box:
                continue
            out[key] = out.get(key, cyc.zero) + v1 * v2
    return {k: v for k, v in out.items() if v != 0}


def pconst(c):
    return {(0, 0, 0): c}


def peq(p, q, box: Box) -> list:
    """Keys in the box where the two truncated series differ."""
    keys = set(k for k in p if k in box) | set(k for k in q if k in box)
    return sorted(k for k in keys if p.get(k, 0) != q.get(k, 0))


class LocalData:
    """Everything Lemma 7.1 needs at one prime, in the field Q(zeta_{12 ell}) (or Q(zeta_60)).

    `eta` is the value eta(p) (a field element, default 1); `rival` replaces eta(p)^t
    by a supplied coefficient f(p^t) (a function t -> field element), for task (2).
    """

    def __init__(self, prime: FPrime, eta=None, gauss_fault=None, extra_N: int = 1):
        self.prime = prime
        self.small = prime.small_field()
        self.cyc = Cyc(math.lcm(prime.big_field().N, extra_N))
        cyc = self.cyc
        self.G_small = gauss_sums(prime, self.small, fault=gauss_fault)
        self.G = {r: self.small.embed(g, cyc) for r, g in self.G_small.items()}
        self.Q = prime.Q
        self.sq = sqrt_int(cyc, self.Q)
        self.alpha = cyc.from_O(prime.pi) / self.sq
        self.abar = cyc.from_O(oconj(prime.pi)) / self.sq
        self.gamma = {r: self.G[r] / self.sq for r in range(1, 6)}
        self.wp = prime.omega_p()
        self.k4 = prime.sym((4, 0))
        self.eta = cyc.one if eta is None else eta
        self._C = {}

    def C(self, t, k, jp):
        """C_p(t, k, j'), computed in the small field Q(zeta_{6 ell}) and embedded."""
        key = (t, k, jp)
        if key not in self._C:
            small = C_p(self.prime, self.G_small, t, k, jp, self.small)
            self._C[key] = self.small.embed(small, self.cyc) if small != 0 else self.cyc.zero
        return self._C[key]

    def a_p(self, eta=None):
        eta = self.eta if eta is None else eta
        return self.abar ** 3 * eta ** 3

    def b_p(self, eta=None):
        eta = self.eta if eta is None else eta
        return self.abar ** 2 * eta ** 2 * self.cyc.zeta6(-self.k4)


def series_local_P(ld: LocalData, j: int, rho_k: int, box: Box, coef=None):
    """The series (local-P) of the paper, truncated to `box`.

    Summand: (-1)^e0 gamma_1^{-e0} eta^e0 (a_p conj(gamma_3))^l rho^{k-t}
             omega_p^{tk - e0 l - l(l-1)/2} C_p(t, k, j + 6m) Q^{-e0/2 - l}.
    With `coef`, eta(p)^{e0+3l} is replaced by coef(t) (the rival placement).
    """
    cyc = ld.cyc
    out = {}
    g1 = ld.gamma[1]
    g3bar = cyc.conj(ld.gamma[3])
    for (t, k, m) in box.keys():
        if t % 3 == 2:
            continue
        e0 = t % 3
        l = (t - e0) // 3
        C = ld.C(t, k, j + 6 * m)
        if C == 0:
            continue
        eta_part = ld.eta ** t if coef is None else coef(t)
        val = (-1) ** e0 * g1 ** (-e0) * eta_part * (ld.abar ** 3 * g3bar) ** l
        val = val * cyc.zeta6(rho_k * (k - t))
        om_exp = t * k - e0 * l - (l * (l - 1)) // 2
        val = val * (ld.wp ** (om_exp % 2)) * C
        val = val / (ld.sq ** e0 * ld.Q ** l)
        if val != 0:
            out[(t, k, m)] = val
    return out


def closed_form_numerator(ld: LocalData, j: int, rho_k: int, eta=None, fault: str | None = None):
    """(1-R)(1-V)(1-W_loc) times Lemma 7.1's P_p (old-eq:5.13a), a polynomial in X, B, V.

    `fault="local_factor"` plants a wrong local factor: R built from a_p instead of
    a_p^2, the second planted fault of the task.  Other variants: "J2_rho",
    "one_minus_Qinv".
    """
    cyc = ld.cyc
    Q = ld.Q
    eta = ld.eta if eta is None else eta
    a = ld.a_p(eta)
    b = ld.b_p(eta)
    rho = cyc.zeta6(rho_k)
    rinv = cyc.zeta6(-rho_k)
    X = {(1, 0, 0): cyc.one}
    Bm = {(0, 1, 0): cyc.one}
    V = {(0, 0, 1): cyc.one}
    one = pconst(cyc.one)

    def mono(c, t, k, m):
        return {(t, k, m): c} if c != 0 else {}

    Rc = (a if fault == "local_factor" else a ** 2) * Q ** 4
    R = mono(Rc, 6, 0, 1)
    W = mono(rho, 0, 1, 0)
    Jtab = {
        0: padd(mono(-eta * rinv, 1, 0, 0), mono(rho * Rc, 6, 1, 1), cyc),
        1: mono(eta, 1, 1, 0),
        2: mono(a * rinv ** 3 * Q * ld.sq * (rho if fault == "J2_rho" else cyc.one), 3, 0, 0),
        3: padd(mono(-eta * b * rinv ** 2 * Q ** 2, 3, 1, 0), mono(b ** 2 * rinv ** 4 * Q ** 2, 4, 0, 0), cyc),
        4: mono(-eta * a * rinv ** 3 * Q ** 2 * ld.sq, 4, 1, 0),
        5: mono(-a ** 2 * Q ** 3, 6, 0, 0),
    }
    J = Jtab[j]
    delta = 1 if j <= 1 else 0
    oneQ = (1 + pari(1) / Q) if fault == "one_minus_Qinv" else (1 - pari(1) / Q)
    one_m_R = padd(one, pscale(R, -cyc.one), cyc)
    one_m_W = padd(one, pscale(W, -cyc.one), cyc)
    one_m_V = padd(one, pscale(V, -cyc.one), cyc)
    term1 = pmul(one_m_R, one_m_W, cyc)
    term2 = pmul(pmul(W, one_m_R, cyc), one_m_V, cyc) if j == 0 else {}
    inner = padd(pscale(R, oneQ * cyc.one), mono(-eta * (Q - 1), 1, 1, delta), cyc)
    inner = padd(inner, pmul(J, one_m_V, cyc), cyc)
    term3 = pmul(one_m_W, inner, cyc)
    return padd(padd(term1, term2, cyc), term3, cyc), {"R": R, "W": W, "V": V, "one": one}


def denominators(ld: LocalData, j: int, rho_k: int, eta=None, fault=None):
    """(1-R)(1-V)(1-W_loc) as a polynomial (R may carry the planted fault)."""
    cyc = ld.cyc
    _, parts = closed_form_numerator(ld, j, rho_k, eta=eta, fault=fault)
    one = parts["one"]
    d = pmul(padd(one, pscale(parts["R"], -cyc.one), cyc), padd(one, pscale(parts["V"], -cyc.one), cyc), cyc)
    return pmul(d, padd(one, pscale(parts["W"], -cyc.one), cyc), cyc)


def lemma_7_1_identity(ld: LocalData, j: int, rho_k: int, box: Box, fault: str | None = None,
                       coef=None, eta=None):
    """Compare (local-P) with the closed form, as exact identities in the truncation box.

    Returns the list of (t, k, m) where (1-R)(1-V)(1-W_loc) * series differs from the
    closed-form numerator.  Empty means the identity holds through the box.
    """
    S = series_local_P(ld, j, rho_k, box, coef=coef)
    num, _ = closed_form_numerator(ld, j, rho_k, eta=eta, fault=fault)
    den = denominators(ld, j, rho_k, eta=eta, fault=fault)
    lhs = pmul(S, den, ld.cyc, box)
    support = [k for k in num if k not in box]
    if support:
        raise ValueError(f"box {box} does not cover the closed-form support {support}")
    return peq(lhs, num, box)


# --- the raw single-prime coefficient, before the paper's phase bookkeeping -----------

def raw_local_coefficient(ld: LocalData, j: int, rho_k: int, t: int, k: int, m: int, coef=None):
    """K at an index supported on one prime, from (local-full-coefficient)'s factors.

    gamma_2(p)^{e0} conj(alpha(p))^t eta(p)^t conj(G(p^t)) R(p^t, p^k) rho^{k-t} C_p,
    times Q^{-e0/2-l} so that it is the coefficient of X^t B^k V^m.  gamma_2 is the
    directly summed cubic Gauss sum; G(p^t) = conj(chi_p(4))^t Gamma(p^t) and the
    bicharacter R = Gamma(ab)/(Gamma(a)Gamma(b)) use Lemma 4.3's four-term value.
    The b_* factors cancel coefficientwise (lines 3941-3949); that cancellation is
    checked separately by the global computation (`global_coefficient`).
    """
    cyc = ld.cyc
    e0 = t % 3
    l = (t - e0) // 3
    pt = pi_pow(ld.prime, t)
    pk = pi_pow(ld.prime, k)
    ptk = pi_pow(ld.prime, t + k)
    Gpt = cyc.zeta6(-ld.k4 * t) * four_term(pt, cyc)
    Rtk = four_term(ptk, cyc) / (four_term(pt, cyc) * four_term(pk, cyc))
    eta_part = ld.eta ** t if coef is None else coef(t)
    val = ld.gamma[2] ** e0 * ld.abar ** t * eta_part * cyc.conj(Gpt) * Rtk
    val = val * cyc.zeta6(rho_k * (k - t)) * ld.C(t, k, j + 6 * m)
    return val / (ld.sq ** e0 * ld.Q ** l)


def raw_vs_series(ld: LocalData, j: int, rho_k: int, box: Box) -> list:
    S = series_local_P(ld, j, rho_k, box)
    bad = []
    for (t, k, m) in box.keys():
        if t % 3 == 2:
            continue
        raw = raw_local_coefficient(ld, j, rho_k, t, k, m)
        if raw != S.get((t, k, m), 0):
            bad.append((t, k, m))
    return bad


def four_term_checks(prime: FPrime, t_max: int) -> dict:
    """Lemma 4.3 against direct summation at c = p^t, and Equation (4.6) at p.

    (4.6): G(p^3) = gamma_3(p) and R(p, p) = gamma_3(p)^2 = chi_p(-1); line 953:
    G(v^2) = chi_v(4), here at v = p.
    """
    small = prime.small_field()
    G = gauss_sums(prime, small)
    out = {}
    sg = {}
    for t in range(1, t_max + 1):
        cyc = Cyc(math.lcm(prime.big_field().N, prime.ell ** t * 6))
        c = pi_pow(prime, t)
        sg[t] = (quad_sum(c, cyc), cyc)
        out[f"Gamma(p^{t}) four-term"] = sg[t][0] == sqrt_int(cyc, onorm(c)) * four_term(c, cyc)
    if t_max >= 3:
        s3, cyc = sg[3]
        out["G(p^3) = gamma_3(p) (4.6)"] = s3 == prime.Q * small.embed(G[3], cyc)
    if t_max >= 2:
        s1, cyc1 = sg[1]
        s2, cyc2 = sg[2]
        s1u = cyc1.embed(s1, cyc2)
        r_pp = s2 / s1u ** 2  # Gamma(p^2)/Gamma(p)^2, the norms cancel
        out["R(p,p) = chi_p(-1) (4.6)"] = r_pp == prime.omega_p() * cyc2.one
        out["R(p,p) = gamma_3(p)^2 (4.6)"] = r_pp * prime.Q == small.embed(G[3], cyc2) ** 2
        out["G(p^2) = chi_p(4) (line 953)"] = (
            cyc2.zeta6(-2 * prime.sym((4, 0))) * s2 == prime.Q * cyc2.zeta6(prime.sym((4, 0)))
        )
    return out


def hp_checks(ld: LocalData, j: int, rho_k: int, box: Box, fault: str | None = None) -> dict:
    """H_p (local-H-definition) and its defect formula (local-H-defect, lines 4139-4142).

    W = chi_p(u) Q^{-w} and D = eta(p) conj(chi_p(u)) Q^{-x}, zero-extended at p | u.
    Checks, exactly in the box: (i) the defect formula; (ii) the cancellation that makes
    1/L(x, eta conj chi(u)) the right factor: H_p - 1 has no X^1 B^0 V^0 term.
    `fault="D_unconjugated"` plants D = eta chi_p(u) Q^{-x} (a wrong Euler factor).
    """
    cyc = ld.cyc
    S = series_local_P(ld, j, rho_k, box)
    one = pconst(cyc.one)
    if j == 0:
        chi_u = cyc.zeta6(rho_k)
        D = {(1, 0, 0): ld.eta * (chi_u if fault == "D_unconjugated" else cyc.conj(chi_u))}
        W = {(0, 1, 0): chi_u}
    else:
        D, W = {}, {}
    V = {(0, 0, 1): cyc.one}
    inv1mD = dict(one)
    power = dict(one)
    for _ in range(box.T):
        power = pmul(power, D, cyc, box)
        inv1mD = padd(inv1mD, power, cyc)
    one_m_V = padd(one, pscale(V, -cyc.one), cyc)
    one_m_W = padd(one, pscale(W, -cyc.one), cyc)
    H = pmul(pmul(pmul(S, one_m_V, cyc, box), one_m_W, cyc, box), inv1mD, cyc, box)
    Hm1 = padd(H, pscale(one, -cyc.one), cyc)
    Sstar = {k: v for k, v in S.items() if k[0] > 0}
    E = padd(Sstar, D, cyc)
    VW = pmul(V, W, cyc)
    rhs = padd(pmul(D, padd(padd(V, W, cyc), pscale(VW, -cyc.one), cyc), cyc), pscale(VW, -cyc.one), cyc)
    rhs = padd(rhs, pmul(pmul(one_m_V, one_m_W, cyc, box), E, cyc, box), cyc)
    rhs = pmul(rhs, inv1mD, cyc, box)
    return {
        "defect formula (local-H-defect)": not peq(Hm1, rhs, box),
        "no X^1 term in H_p - 1 (the -D cancellation)": Hm1.get((1, 0, 0), 0) == 0,
        "Hm1": Hm1,
    }


