def prime_battery(ell: int, box: Box = Box(13, 2, 4), table_box=(13, 2, 29), lift_t: int = 2) -> dict:
    """Every prime-level check of task (1) at the prime above `ell`, plus both planted faults.

    Returns a dict of named booleans; the true objects must give True everywhere and the
    two planted faults must each give at least one False.
    """
    p = FPrime(ell)
    out = {}
    out["Lemma 4.2 (21 identities)"] = all(lemma_4_2_checks(p).values())
    out["lift = direct summation"] = all(lift_checks(p, lift_t).values())
    T, K, J = table_box
    out["C_p definition = table"] = all(scalar_table_checks(p, T, K, J, direct_t_max=1).values())
    out["four-term and (4.6)"] = all(four_term_checks(p, 2).values())
    ld = LocalData(p)
    out["Lemma 7.1 closed form, all j and rho"] = all(
        lemma_7_1_identity(ld, j, rk, box) == [] for j in range(6) for rk in range(6))
    out["raw coefficient = (local-P) summand"] = all(
        raw_vs_series(ld, j, rk, Box(min(box.T, 13), 2, 3)) == [] for j in range(6) for rk in (0, 1))
    out["H_p defect and -D cancellation"] = all(
        (lambda h: h["defect formula (local-H-defect)"] and h["no X^1 term in H_p - 1 (the -D cancellation)"])(
            hp_checks(ld, j, rk, box)) for j in range(6) for rk in range(6))
    # planted faults: they must fire
    out["FAULT gauss_sign caught by Lemma 4.2"] = not all(lemma_4_2_checks(p, fault="gauss_sign").values())
    ldf = LocalData(p, gauss_fault="gauss_sign")
    out["FAULT gauss_sign caught by the raw check (every row)"] = all(
        raw_vs_series(ldf, j, 1, Box(7, 1, 2)) for j in range(6))
    out["FAULT local_factor caught by the closed-form check (every row)"] = all(
        lemma_7_1_identity(ld, j, 1, box, fault="local_factor") for j in range(6))
    return out


