# prime is the summand of (local-P) (lines 3997-4006).


def index_elt(index: dict):
    x = ONE
    for p, e in index.items():
        x = omul(x, pi_pow(p, e))
    return x


def index_mul(*indices):
    out = {}
    for ind in indices:
        for p, e in ind.items():
            out[p] = out.get(p, 0) + e
    return {p: e for p, e in out.items() if e}


def chi_of_index(index: dict, x):
    """Exponent of chi_c(x) = prod chi_p(x)^{v_p(c)} (line 635), or None (zero)."""
    total = 0
    for p, e in index.items():
        k = chi_power(p, x, e)
        if k is None:
            return None
        total += k
    return total % 6


class GlobalData:
    """The fixed arithmetic datum: S = {(2), (lambda)} plus optional inert primes, b_*, xi.

    `xi` is a residue character modulo b_* whose restriction to each prime of S is
    nonprincipal and of order dividing six (lines 3349-3355): order three on
    (O/2)^x = F_4^x, the quadratic character of F_3 at lambda, and the quadratic
    character at an added inert prime (via PARI's sextic symbol cubed).
    """

    def __init__(self, extra_inert=()):
        self.extra = [FPrime(ell) for ell in extra_inert]
        b = omul((2, 0), LAMBDA)
        for p in self.extra:
            b = omul(b, p.pi)
        self.bstar = b
        self.q_bstar = onorm(b)

    @staticmethod
    def xi_2(d):
        """The order-three character of (O/2)^x = F_4^x: omega^k mod 2 -> zeta_6^{2k}."""
        r2 = (d[0] % 2, d[1] % 2)
        return None if r2 == (0, 0) else {(1, 0): 0, (0, 1): 2, (1, 1): 4}[r2]

    @staticmethod
    def xi_lambda(d):
        """The quadratic character of O/lambda = F_3 (omega = 1 mod lambda)."""
        r3 = (d[0] + d[1]) % 3
        return None if r3 == 0 else (0 if r3 == 1 else 3)

    def xi(self, d):
        """Exponent of xi(d) in Z/6, or None when d meets S."""
        parts = [self.xi_2(d), self.xi_lambda(d)]
        for p in self.extra:
            k = p.sym(d)
            parts.append(None if k is None else 3 * k)  # quadratic = sextic symbol cubed
        if None in parts:
            return None
        return sum(parts) % 6

    def needed_N(self, moduli, ells, extra=1):
        n = math.lcm(12, extra)
        for ell in ells:
            n = math.lcm(n, 4 * ell)
        for m in moduli:
            for gen in (ONE, (0, 1)):
                n = math.lcm(n, echar(gen, m).denominator)
        return n

    def g_xi_chiA(self, A_index: dict, y, cyc: Cyc):
        """g_{xi chi_A}(b_* A, y) = sum_{d mod b_* A} xi(d) chi_A(d) e(y d/(b_* A))."""
        M = omul(self.bstar, index_elt(A_index))
        counts = {}
        for d in Residues(M):
            kx = self.xi(d)
            if kx is None:
                continue
            ka = chi_of_index(A_index, d)
            if ka is None:
                continue
            e = cyc.sextic(kx + ka) + cyc.exp_of(echar(omul(y, d), M))
            counts[e] = counts.get(e, 0) + 1
        return cyc.from_counts(counts)

    def F(self, s_index: dict, A_index: dict, H, cyc: Cyc):
        """F(s, A, H) of (local-F): sum over d mod s with H = b_* A d (mod s)."""
        s = index_elt(s_index)
        A = index_elt(A_index)
        bA = omul(self.bstar, A)
        total = cyc.zero
        for d in Residues(s):
            diff = osub(H, omul(bA, d))
            if not odivides(s, diff):
                continue
            ks = chi_of_index(s_index, d)
            if ks is None:
                continue
            total = total + cyc.zeta6(ks) * self.g_xi_chiA(A_index, odiv(diff, s), cyc)
        return total

    def coefficient(self, c: dict, n: dict, s: dict, a: dict, u, cyc: Cyc, eta=None):
        """K_eta(c, n, s, a; u) from (local-full-coefficient), exactly.

        `eta` maps an index dict to a field element (default: the trivial character).
        """
        assert all(e == 1 for e in c.values()), "c must be squarefree"
        A_index = index_mul(c, {p: 3 * e for p, e in n.items()})
        A = index_elt(A_index)
        sv = index_elt(s)
        H = omul(u, opow(index_elt(a), 6))
        Fv = self.F(s, A_index, H, cyc)
        if Fv == 0:
            return cyc.zero
        k_sb = chi_of_index(s, self.bstar)
        g_b = self.g_xi_chiA({}, ONE, cyc)  # = sqrt(q_{b_*}) tau
        xs, xu, xA = self.xi(sv), self.xi(u), self.xi(A)
        assert None not in (k_sb, xs, xu, xA)
        val = Fv * cyc.zeta6(k_sb) / (g_b * cyc.zeta6(xs) * cyc.zeta6(-xu))
        if c:
            cprimes = list(c.keys())
            qc = onorm(index_elt(c))
            val = val * gauss_index(cprimes, 2, cyc) / sqrt_int(cyc, qc)
        qA = onorm(A)
        alphaA = cyc.from_O(A) / sqrt_int(cyc, qA) if qA > 1 else cyc.one
        k4 = chi_of_index(A_index, (4, 0))
        GA = cyc.zeta6(-k4) * four_term(A, cyc)
        kXi = (xA + chi_of_index(A_index, self.bstar)) % 6
        RAs = four_term(omul(A, sv), cyc) / (four_term(A, cyc) * four_term(sv, cyc))
        etaA = cyc.one if eta is None else eta(A_index)
        val = val * cyc.conj(alphaA) * cyc.conj(GA) * etaA * cyc.zeta6(-kXi) * RAs
        return val


def s_prime_claims(gd: GlobalData) -> dict:
    """What the paper claims at the primes of S (above 6), lines 579-582 and 3349-3367, 3755.

    The sextic symbol, Lemma 4.2 and Lemma 7.1 are not claimed there and are not run.
    """
    cyc = Cyc(gd.needed_N([gd.bstar], []))
    out = {}
    # units have distinct residues mod 3 (primary generators are unique), line 579
    out["six units distinct mod 3"] = len({(u[0] % 3, u[1] % 3) for u in UNITS6}) == 6
    # xi is a character of (O/b_*)^x, nonprincipal on each prime factor, order | 6
    res = [d for d in Residues(gd.bstar) if gd.xi(d) is not None]
    mult = all(
        gd.xi(Residues(gd.bstar).reduce(omul(x, y))) == (gd.xi(x) + gd.xi(y)) % 6
        for x in res for y in res
    )
    out["xi multiplicative on (O/b_*)^x"] = mult
    out["xi at (2) has order 3 on F_4^x"] = sorted(gd.xi_2(d) for d in [(1, 0), (0, 1), (1, 1)]) == [0, 2, 4]
    out["xi at lambda is the quadratic character of F_3"] = [gd.xi_lambda(d) for d in [(1, 0), (2, 0)]] == [0, 3]
    for p in gd.extra:
        vals = {3 * p.sym(d) % 6 for d in p.residues if p.sym(d) is not None}
        out[f"xi at the added prime of norm {p.Q} is nonprincipal"] = vals == {0, 3}
    gb = gd.g_xi_chiA({}, ONE, cyc)
    out["|tau| = 1 (line 3367)"] = gb * cyc.conj(gb) == gd.q_bstar * cyc.one
    # the primitive Gauss sum vanishes unless (H, S) = 1, line 3755
    vanish = True
    for H in [(0, 0), (2, 0), LAMBDA, (2, 2), (3, 0), omul((2, 0), LAMBDA)] + [p.pi for p in gd.extra]:
        if gd.g_xi_chiA({}, H, cyc) != 0:
            vanish = False
    out["g_xi(b_*, H) = 0 when H meets S (line 3755)"] = vanish
    out["g_xi(b_*, h) = conj(xi(h)) g_xi(b_*, 1) for h prime to S"] = all(
        gd.g_xi_chiA({}, h, cyc) == cyc.zeta6(-gd.xi(h)) * gb for h in res
    )
    return out


def local_summand(ld: LocalData, j: int, rho_k: int, t: int, k: int, m: int, coef=None):
    """One coefficient of (local-P) (the monomial X^t B^k V^m), or zero."""
    if t % 3 == 2:
        return ld.cyc.zero
    return series_local_P(ld, j, rho_k, Box(t, k, m), coef=coef).get((t, k, m), ld.cyc.zero)


def single_prime_index(prime, t, k, m):
    e0 = t % 3
    l = (t - e0) // 3
    c = {prime: 1} if e0 else {}
    n = {prime: l} if l else {}
    s = {prime: k} if k else {}
    a = {prime: m} if m else {}
    return c, n, s, a


def norm_character_eta(dirichlet):
    """eta(ideal) = chi(N ideal) for a Dirichlet character given as a function of n."""
    def eta(index, cyc):
        return dirichlet(onorm(index_elt(index)), cyc)
    return eta


def global_vs_local(prime: FPrime, u0_k: int, j: int, cases, eta_dirichlet=None, extra_inert=()):
    """Global K at single-prime indices against Q^{e0/2+l} times the (local-P) summand.

    u = pi^j * zeta_6^{u0_k}; rho = chi_p(zeta_6^{u0_k}).  `cases` are (t, k, m).
    Returns {(t,k,m): (global == local, global != 0)}.
    """
    gd = GlobalData(extra_inert)
    u = omul(pi_pow(prime, j), UNITS6[u0_k % 6])
    moduli = [gd.bstar]
    for (t, k, m) in cases:
        c, n, s, a = single_prime_index(prime, t, k, m)
        A = index_mul(c, {p: 3 * e for p, e in n.items()})
        moduli += [omul(gd.bstar, index_elt(A)), index_elt(c) if c else ONE, index_elt(s) if s else ONE]
    N = gd.needed_N(moduli, [prime.ell])
    cyc = Cyc(N)
    eta_val = None
    eta_fn = None
    if eta_dirichlet is not None:
        eta_val = eta_dirichlet(prime.Q, cyc)
        eta_fn = (lambda index, cyc=cyc: eta_dirichlet(onorm(index_elt(index)), cyc))
    ld = LocalData(prime, eta=eta_val, extra_N=N)
    assert ld.cyc is cyc
    rho_k = prime.sym(UNITS6[u0_k % 6])
    out = {}
    for (t, k, m) in cases:
        c, n, s, a = single_prime_index(prime, t, k, m)
        K = gd.coefficient(c, n, s, a, u, cyc, eta=eta_fn)
        e0 = t % 3
        l = (t - e0) // 3
        loc = local_summand(ld, j, rho_k, t, k, m) * ld.sq ** e0 * ld.Q ** l
        out[(t, k, m)] = (K == loc, K != 0)
    return out


def separation_checks(p: FPrime, q: FPrime, u, local_cases, eta_dirichlet=None, extra_inert=(),
                      rival=None):
    """K(I_p I_q) = K(I_p) K(I_q) for indices I_p at p and I_q at q (line 3994).

    `local_cases` lists (t, k, m) with t <= 1 (c squarefree, n = 1).  With `rival`
    (a function of the norm), eta is replaced by the rival coefficient f(A) = a(N A):
    then the ratio K(I_p I_q)/(K(I_p) K(I_q)) is reported instead of a boolean.
    """
    gd = GlobalData(extra_inert)
    idx = []
    for (t, k, m) in local_cases:
        assert t in (0, 1) and m == 0
        idx.append((t, k))
    moduli = [gd.bstar]
    for (t1, k1) in idx:
        for (t2, k2) in idx:
            c = index_mul({p: 1} if t1 else {}, {q: 1} if t2 else {})
            s = index_mul({p: k1} if k1 else {}, {q: k2} if k2 else {})
            moduli += [omul(gd.bstar, index_elt(c)), index_elt(c), index_elt(s)]
    N = gd.needed_N(moduli, sorted({p.ell, q.ell}), extra=20 if rival is not None else 1)
    cyc = Cyc(N)
    if rival is not None:
        eta_fn = (lambda index, cyc=cyc: rival(onorm(index_elt(index)), cyc))
    elif eta_dirichlet is not None:
        eta_fn = (lambda index, cyc=cyc: eta_dirichlet(onorm(index_elt(index)), cyc))
    else:
        eta_fn = None
    single = {}
    for prime in (p, q):
        for (t, k) in idx:
            c = {prime: 1} if t else {}
            s = {prime: k} if k else {}
            single[(prime, t, k)] = gd.coefficient(c, {}, s, {}, u, cyc, eta=eta_fn)
    out = {}
    for (t1, k1) in idx:
        for (t2, k2) in idx:
            c = index_mul({p: 1} if t1 else {}, {q: 1} if t2 else {})
            s = index_mul({p: k1} if k1 else {}, {q: k2} if k2 else {})
            K = gd.coefficient(c, {}, s, {}, u, cyc, eta=eta_fn)
            prod = single[(p, t1, k1)] * single[(q, t2, k2)]
            out[((t1, k1), (t2, k2))] = (K, prod)
    return out, cyc


# ---------------------------------------------------------------------------
# F. Rivals: the Davenport-Heilbronn combination and the Epstein zeta of D = -15
# ---------------------------------------------------------------------------
#
# Placement.  The identity reads the target only through eta(A) in the coefficient
# (local-full-coefficient); the paper places a Dirichlet character chi into that slot
# as eta(a) = chi(N a) (in the proof of prop:hecke-dirichlet-transfer, line 6725).
# This lane extends that rule, stated for characters only, to a rival's Dirichlet
# coefficients a(n): f(a) = a(N a) goes in the slot.  Because
# K is linear in eta, for DH this is c_1 (chi o N) + c_2 (chibar o N), a linear
# combination of two Hecke characters of F; the rival's bad primes join S.

#: zeta/epstein.py's pinned 40-digit kappa (a reference only; it is re-derived here).
KAPPA_REF = "0.2840790438404122960282918323931261690911"


_KAPPA: dict = {}


def dh_kappa(cyc: Cyc):
    """kappa = (sqrt(10 - 2 sqrt 5) - 2)/(sqrt 5 - 1) exactly in cyc (20 | N)."""
    if cyc.N in _KAPPA:
        return _KAPPA[cyc.N]
    s5 = sqrt_int(cyc, 5)
    s = -2 * cyc.i() * (cyc.root(1, 10) - cyc.root(-1, 10))  # 4 sin(pi/5)
    assert s * s == 10 - 2 * s5
    assert cyc.number(s).real > 0
    kappa = (s - 2) / (s5 - 1)
    assert abs(cyc.number(kappa) - float(KAPPA_REF)) < 1e-14
    _KAPPA[cyc.N] = kappa
    return kappa


def dh_coefficient(n: int, cyc: Cyc):
    """The DH Dirichlet coefficient: 1, kappa, -kappa, -1, 0 for n = 1, 2, 3, 4, 0 mod 5.

    This is 2 Re(c chi(n)) with c = (1 - i kappa)/2 and chi(2) = i, as in
    zeta/epstein.py's `dh_coefficient`.
    """
    k = dh_kappa(cyc)
    return {1: cyc.one, 2: k, 3: -k, 4: -cyc.one, 0: cyc.zero}[n % 5]


def _divisors(n):
    divs = [1]
    m = n
    for p in _prime_factors(n):
        e = 0
        while m % p == 0:
            m //= p
            e += 1
        divs = [d * p ** i for d in divs for i in range(e + 1)]
    return sorted(divs)


def epstein_coefficient(n: int) -> Fraction:
    """r_{Q0}(n)/2 for Q0 = x^2 + xy + 4y^2, from zeta L(chi_-15) + L(chi_-3) L(chi_5)."""
    s1 = sum(int(pari.kronecker(-15, d)) for d in _divisors(n))
    s2 = sum(int(pari.kronecker(-3, d)) * int(pari.kronecker(5, n // d)) for d in _divisors(n))
    return Fraction(s1 + s2, 2)


def epstein_count(n: int) -> int:
    """r_{Q0}(n) by direct lattice count: #{(x, y) : x^2 + xy + 4y^2 = n}."""
    count = 0
    y = 0
    while 15 * y * y <= 4 * n:
        for ys in ({y, -y} if y else {0}):
            disc = 4 * n - 15 * ys * ys
            s = math.isqrt(disc)
            if s * s == disc:
                for x in {(-ys + s), (-ys - s)}:
                    if x % 2 == 0:
                        count += 1
        y += 1
    return count


def rival_coefficient(name: str):
    if name == "DH":
        return lambda n, cyc: dh_coefficient(n, cyc)
    if name == "Epstein-15":
        return lambda n, cyc: pari(str(epstein_coefficient(n))) * cyc.one
    raise ValueError(name)


#: The paper's family table (eq:local-family-table, lines 4086-4100), entry names.
def family_entry(t: int, k: int, m: int, j: int) -> str:
    if t == 0:
        return "1/(1-V)" if k == 0 else "W_loc/(1-W_loc) (j = 0)"
    r6 = t % 6
    if r6 == 0:
        r = t // 6 - 1
        if k == 0:
            return f"R(1-Q^-1) V^(m-r-1), family (0,2r+2), r={r}" if m >= r + 1 else "J_5 = -a_p^2 Q^(3-6x) (j = 5)"
        return f"W_loc R (J_0, second term), family (0,2r+2), r={r}"
    if r6 == 1:
        r = (t - 1) // 6
        if k == 0:
            return f"-eta rho^-1 Q^-x (J_0, the -D term), family (1,2r), r={r}"
        return f"eta Q^(-x-w) (J_1) or -eta (Q-1) Q^(-x-w) V^(m-r), family (1,2r), r={r}"
    if r6 == 3:
        r = (t - 3) // 6
        return (f"a_p rho^-3 Q^(3/2-3x) (J_2), family (0,2r+1), r={r}" if k == 0
                else f"-eta b_p rho^-2 Q^(2-3x-w) (J_3), family (0,2r+1), r={r}")
    r = (t - 4) // 6
    return (f"b_p^2 rho^-4 Q^(2-4x) (J_3), family (1,2r+1), r={r}" if k == 0
            else f"-eta a_p rho^-3 Q^(5/2-4x-w) (J_4), family (1,2r+1), r={r}")


def closed_form_series(ld: LocalData, j: int, rho_k: int, box: Box, eta=None):
    """Lemma 7.1's P_p expanded as a truncated power series in X, B, V."""
    cyc = ld.cyc
    num, parts = closed_form_numerator(ld, j, rho_k, eta=eta)
    one = parts["one"]
    inv = dict(one)
    for factor in (parts["R"], parts["V"], parts["W"]):
        geo = dict(one)
        pw = dict(one)
        for _ in range(box.T + box.K + box.M + 1):
            pw = pmul(pw, factor, cyc, box)
            if not pw:
                break
            geo = padd(geo, pw, cyc)
        inv = pmul(inv, geo, cyc, box)
    return pmul(num, inv, cyc, box)


def rival_local(name: str, prime: FPrime, box: Box, rho_ks=(0,)) -> dict:
    """The rival's local series against Lemma 7.1's closed form at eta(p) = f(p).

    f(p^t) = a(N p^t).  The t = 1 coefficient forces eta(p) = f(p) in every row (it is
    -eta rho^-1 for j = 0, eta for j = 1, and -eta (Q-1) for j >= 2), so a mismatch
    at a later monomial is a failure of the closed form for every choice of eta(p).
    Returns, per row j, the first monomial where the two differ and its table entry.
    """
    fN = rival_coefficient(name)
    cyc = Cyc(math.lcm(prime.big_field().N, 20))
    ld = LocalData(prime, extra_N=20)
    assert ld.cyc is cyc
    coef = lambda t: fN(prime.Q ** t, cyc)
    eta = coef(1)
    out = {}
    for j in range(6):
        for rk in rho_ks:
            # The multiplier (1-R)(1-V)(1-W_loc) has constant term 1, so the
            # lexicographically first key where the multiplied forms differ is the first
            # monomial where the series themselves differ.
            diff = lemma_7_1_identity(ld, j, rk, box, coef=coef, eta=eta)
            first = diff[0] if diff else None
            out[(j, rk)] = {
                "first": first,
                "entry": family_entry(*first, j) if first else None,
                "n_diff": len(diff),
            }
    return out


def rival_prime_powers(name: str, ell: int, t_max: int = 13) -> dict:
    """f(p^t) against f(p)^t for t in {1, 3, 4, 6, 7, ...} (t = e0 + 3l), as floats."""
    cyc = Cyc(math.lcm(12 * ell, 20))
    fN = rival_coefficient(name)
    f1 = fN(ell, cyc)
    rows = {}
    for t in range(1, t_max + 1):
        if t % 3 == 2:
            continue
        ft = fN(ell ** t, cyc)
        rows[t] = (cyc.number(ft).real, cyc.number(f1 ** t).real, ft == f1 ** t)
    return rows


def rival_cross_term(name: str, p: FPrime, q: FPrime, u=ONE):
    """The u-row coefficient at c = p q against K(p) K(q), with the rival in the eta slot.

    S = {(2), (lambda), (5)}: 5 is the DH modulus and divides D = -15.  Returns
    (K(pq), K(p) K(q), f(pq), f(p) f(q)) as complex numbers and the exact verdict.
    """
    fN = rival_coefficient(name)
    out, cyc = separation_checks(p, q, u, [(0, 0, 0), (1, 0, 0)], extra_inert=(5,), rival=fN)
    K, prod = out[((1, 0), (1, 0))]
    fpq = fN(onorm(omul(p.pi, q.pi)), cyc)
    fp, fq = fN(p.Q, cyc), fN(q.Q, cyc)
    # the same coefficient for the trivial character: the phase that multiplies f
    out1, cyc1 = separation_checks(p, q, u, [(0, 0, 0), (1, 0, 0)], extra_inert=(5,))
    K1, prod1 = out1[((1, 0), (1, 0))]
    return {
        "K(pq)": cyc.number(K), "K(p)K(q)": cyc.number(prod),
        "f(pq)": cyc.number(fpq), "f(p)f(q)": cyc.number(fp * fq),
        "separates": K == prod,
        "trivial character separates": K1 == prod1,
        "K(pq) = f(pq) K_1(pq)": K == fpq * cyc1.embed(K1, cyc) if cyc.N % cyc1.N == 0 else None,
    }


# --- which step fails where: both steps, on the same primes ---------------------------
#
# Separation reduces to the coefficients: K is linear in eta and reads it only through
# eta(A), and the trivial character separates (`rival_cross_term` checks both at every
# computed pair), so K_f(pq) = K_f(p) K_f(q) exactly when f(pq) = f(p) f(q).  The u = 1
# row's coefficient at X^6 V is f(p^6) times the character-case coefficient, which is
# nonzero at every prime (it carries C_p(6, 0, 6) = Q^6 - Q^5), and below t = 6 that row
# reads only f(p^0) and f(p^1); so that row fails at X^6 V exactly when f(p^6) != f(p)^6.

def dh_residue_structure() -> dict:
    """The placed DH coefficient f(a) = a(N a), exhaustively over N p mod 5 (exact).

    f depends only on N a mod 5.  For each nonzero residue x: `chi_real[x]` is whether
    chi(x) is real, read off as chi^2(x) = (x/5) = 1 (chi^2 is the quadratic character);
    `local[x]` is f(p^t) = f(p)^t for t = 1..13 (DH agrees with a Hecke character on the
    powers of p); `sixth[x]` is f(p^6) = f(p)^6.  For each pair of residues,
    `pairs[(x, y)]` is f(pq) = f(p) f(q).
    """
    cyc = Cyc(20)
    res = (1, 2, 3, 4)

    def a(n):
        return dh_coefficient(n, cyc)

    return {
        "chi_real": {x: int(pari.kronecker(x, 5)) == 1 for x in res},
        "local": {x: all(a(x ** t) == a(x) ** t for t in range(1, 14)) for x in res},
        "sixth": {x: a(x ** 6) == a(x) ** 6 for x in res},
        "pairs": {(x, y): a(x * y) == a(x) * a(y) for x in res for y in res},
        "inert norms": sorted({(x * x) % 5 for x in res}),
    }


def epstein_split_structure(ell_max: int = 200) -> dict:
    """The placed Epstein coefficient f(a) = r(N a)/2 at split primes of F, exactly.

    For each rational prime ell = 1 mod 3 below `ell_max` (each splits as p pbar in O):
    f(p^t) = r(ell^t)/2 for both primes above ell.  Reports whether f(p^6) = f(p)^6 (the
    u = 1 coefficient at X^6 V), whether f(p pbar) = f(ell^2) equals f(p) f(pbar) =
    f(ell)^2 (separation at the conjugate pair), and, for every pair of distinct such
    primes ell, ell', whether f(ell ell') = f(ell) f(ell') (separation across distinct
    rational primes).  Also checks f(ell^t) = sum_{i <= t} chi_5(ell)^i for t <= 6.
    """
    ells = [ell for ell in range(7, ell_max) if ell % 3 == 1 and _prime_factors(ell) == [ell]]
    f = epstein_coefficient
    closed = all(
        f(ell ** t) == sum(int(pari.kronecker(5, ell)) ** i for i in range(t + 1))
        for ell in ells for t in range(7)
    )
    return {
        "ells": ells,
        "f(p^t) = sum chi_5(ell)^i": closed,
        "sixth": {ell: f(ell ** 6) == f(ell) ** 6 for ell in ells},
        "conjugate pair separates": {ell: f(ell ** 2) == f(ell) ** 2 for ell in ells},
        "distinct pairs separate": {
            (e1, e2): f(e1 * e2) == f(e1) * f(e2) for i, e1 in enumerate(ells) for e2 in ells[i + 1:]
        },
    }


