# An index is a dict {FPrime: exponent}.  K_eta(c, n, s, a; u) is built from its
# definition: the full Poisson coefficient F(s, A, H) of (local-F) (lines 3742-3745)
# as a sum over d mod s of complete Gauss sums modulo b_* A, the normalizations of
