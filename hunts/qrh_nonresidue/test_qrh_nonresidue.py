def test_constants_match_mpmath_and_functional_equation(C):
    with mp.workdps(40):
        c = mp.mpf(1) / 4
        s0 = mp.mpf(2)
        lz = mp.zeta(s0, derivative=1) / mp.zeta(s0)
        A_chi = -lz - mp.log(mp.pi) / 2 + mp.digamma((s0 + 1) / 2) / 2
        A_zeta = 1 / s0 + 1 / (s0 - 1) - mp.log(mp.pi) / 2 + mp.digamma(s0 / 2) / 2 + lz
        lz1 = mp.zeta(1 + c, derivative=1) / mp.zeta(1 + c)
        fe = -lz1 + mp.log(mp.pi) - mp.digamma(-c / 2) / 2 - mp.digamma((1 + c) / 2) / 2
    assert C.A_chi.contains(arb(mp.nstr(A_chi, 30))) or abs(float(C.A_chi.mid()) - float(A_chi)) < 1e-14
    assert abs(float(C.A_zeta.mid()) - float(A_zeta)) < 1e-14
    # -zeta'/zeta(-c) from Arb's continuation versus the functional equation
    assert abs(float(C.Fz.mid()) + float(fe)) < 1e-14
    # sum over zeta zeros of Re 1/(2 - rho) is positive and small
    assert 0.06 < float(C.A_zeta.mid()) < 0.08


def test_K_of_x_constant_regime_and_grid_bound(C):
    big = E.K_of_x(C, arb(6))
    assert big.overlaps(1 / (arb(7) / 8 + arb(1) / 4))
    small = E.K_of_x(C, arb(2))
    # below L_star the zeros near Re s = 1/8 dominate and K grows
    assert _lo(small) > _lo(big)
    # brute check of the supremum at log x = 2
    b = np.linspace(1 / 8, 7 / 8, 20001)
    f = np.exp((b - 7 / 8) * 2) * (2 - b) / (b + 0.25) ** 2
    assert f.max() <= float(small.upper())


def test_theorem1_closed_margin_positive_at_L0(C):
    L0 = arb(5) / 2
    m = E.margin_closed(C, L0)
    assert _lo(m) > 0.09
