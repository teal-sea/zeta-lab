def test_sieve_inequality_pointwise():
    """Lemma 7's combinatorial step, exhaustively over all units for small p."""
    for p in (31, 211, 421, 2311):
        qs = T.factor_small(p - 1)
        g = next(a for a in range(2, p) if T.is_primitive_root_int(a, p, qs))
        dlog = {}
        x = 1
        for k in range(p - 1):
            dlog[x] = k
            x = x * g % p
        for j in range(len(qs)):
            core, rest = qs[:j], qs[j:]
            if len(rest) < 1:
                continue
            for a in range(1, p):
                k = dlog[a]
                free = lambda ms: all(k % m for m in ms)  # noqa: E731
                lhs = 1 if free(qs) else 0
                rhs = sum(1 for r in rest if free(core + [r])) - (len(rest) - 1) * (1 if free(core) else 0)
                assert lhs >= rhs


def test_miller_liars_lie_in_proper_subgroup():
    """Lemma 8 for every odd composite n < 1500."""
    for n in range(9, 1500, 2):
        if T._is_probable_prime(n):
            continue
        units = [a for a in range(1, n) if gcd(a, n) == 1]
        liars = [a for a in units if T.is_strong_liar(a, n)]
        d, s = n - 1, 0
        while d % 2 == 0:
            d //= 2
            s += 1
        js = [r for r in range(s) for b in liars if pow(b, (2 ** r) * d, n) == n - 1]
        m = (2 ** max(js)) * d
        H = {a for a in units if pow(a, m, n) in (1, n - 1)}
        if len(T.factor_small(n)) == 1:
            H = {a for a in units if pow(a, n - 1, n) == 1}
        assert set(liars) <= H and len(H) < len(units)


def test_tables_against_bounds_and_python_ints():
    N = 200_000
    isp = T.prime_sieve(N)
    spf = T.spf_sieve(N)
    ps = np.nonzero(isp)[0].astype(np.int64)
    odd = ps[ps > 2]
    nr = T.least_nonresidues(odd, ps[:200])
    assert (nr <= np.log(odd.astype(float)) ** 8).all()
    Fm = T.distinct_prime_factors(odd - 1, spf)
    gs = T.least_primitive_roots(odd, Fm, [int(x) for x in ps[:300]])
    oddn = np.arange(9, N + 1, 2)
    comp = oddn[~isp[oddn]]
    w = T.least_strong_witness(comp)
    assert (w <= np.log(comp.astype(float)) ** 8).all()
    rng = np.random.default_rng(1)
    for i in rng.choice(len(odd), 60, replace=False):
        p = int(odd[i])
        assert T.legendre_nonresidue_int(p) == nr[i]
        assert T.least_primitive_root_int(p, prime_only=True) == gs[i]
        lam = E.best_sieve_factor(T.factor_small(p - 1))
        assert gs[i] <= (float(max(lam, 1)) * math.log(p)) ** 8
    for i in rng.choice(len(comp), 60, replace=False):
        assert T.least_strong_witness_int(int(comp[i])) == w[i]
    assert T.least_strong_witness_int(2047) == 3
    assert T.least_strong_witness_int(1373653) == 5


