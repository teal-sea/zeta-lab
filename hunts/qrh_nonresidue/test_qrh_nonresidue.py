def test_generation_bound_equals_max_character_nonresidue():
    """Lemma 6 by brute force: characters of (Z/qZ)^* via a discrete log basis."""
    for q in (15, 16, 21, 35, 40):
        units = [a for a in range(1, q) if gcd(a, q) == 1]
        primes = [p for p in range(2, 200) if all(p % d for d in range(2, p))]
        N = T.generation_bound(q, primes)
        # subgroup generated by primes < N is proper, by primes <= N is everything
        def span(gens):
            H = {1}
            for g in gens:
                while True:
                    new = {(h * g) % q for h in H} | H
                    if new == H:
                        break
                    H = new
            return H
        below = span([p % q for p in primes if p < N and q % p])
        upto = span([p % q for p in primes if p <= N and q % p])
        assert len(upto) == len(units) and len(below) < len(units)


