def _S_zeta(x, c):
    """Direct prime-power sum S(1; x) = sum Lambda(n) (n/x)^c log(x/n)."""
    total = mp.mpf(0)
    for n in range(2, int(x) + 1):
        f = T.factor_small(n)
        if len(f) == 1:
            total += mp.log(f[0]) * (mp.mpf(n) / x) ** c * mp.log(x / n)
    return total


def test_explicit_formula_normalisation_for_zeta(C):
    """Lemma 2 for zeta at x = 100, c = 1/4, with 1000 zeros and the residue at -c.

    Truncation tail is below 0.02; flipping the sign of the residue term
    (a planted convention error) moves the right side by about 5.
    """
    zeros = json.loads((HERE.parents[1] / "data" / "zeros_1000.json").read_text())["zeros"]
    with mp.workdps(25):
        x, c = mp.mpf(100), mp.mpf(1) / 4
        lhs = _S_zeta(x, c)
        zsum = mp.mpf(0)
        for g in zeros:
            rho = mp.mpf(1) / 2 + 1j * mp.mpf(g)
            zsum += 2 * mp.re(x ** rho / (rho + c) ** 2)
        triv = mp.nsum(lambda k: x ** (-2 * k) / (2 * k - c) ** 2, [1, mp.inf])
        z0, z1, z2 = (mp.zeta(-c, derivative=k) for k in range(3))
        Fz, Fz1 = -z1 / z0, -(z2 / z0 - (z1 / z0) ** 2)
        res = x ** (-c) * (Fz1 + Fz * mp.log(x))
        rhs = x / (1 + c) ** 2 - zsum - triv + res
        assert abs(lhs - rhs) < 0.03
        assert abs(lhs - (rhs - 2 * res)) > 1


@pytest.mark.parametrize("q,chi,a", [(4, [0, 1, 0, -1], 1), (5, [0, 1, -1, -1, 1], 0)])
def test_residue_formula_for_characters(q, chi, a):
    """Lemma 5's expression for F(-c) = -L'/L(-c) against mpmath's continuation."""
    with mp.workdps(30):
        c = mp.mpf(1) / 4
        L0 = mp.dirichlet(-c, chi)
        L1 = mp.dirichlet(-c, chi, derivative=1)
        direct = -L1 / L0
        Lp = mp.dirichlet(1 + c, chi, derivative=1) / mp.dirichlet(1 + c, chi)  # real chi
        formula = Lp + mp.log(q / mp.pi) + mp.digamma((a - c) / 2) / 2 + mp.digamma((1 + a + c) / 2) / 2
        assert abs(direct - formula) < mp.mpf(10) ** -20
        C = E.constants(F(7, 8), F(1, 4))
        assert abs(direct) <= mp.log(q) + mp.mpf(float(C.R1.upper()))


def test_quartic_kernel_constant_closed_form():
    """sup over gamma of |W|/Re 1/(sigma0-rho) at beta = theta, W = (s+c)^-4."""
    th, c = 7 / 8, 0.02
    D = th + c
    d = D / math.sqrt(3)
    assert d > 1 / 8  # sigma0 = theta + d > 1, so Lemma 3's bound applies
    g = np.concatenate([np.linspace(0, 10, 200001), np.logspace(1, 5, 2000)])
    ratio = (d * d + g * g) / (d * (D * D + g * g) ** 2)
    assert abs(ratio.max() - 3 * math.sqrt(3) / (8 * D ** 3)) < 1e-8
    # other choices of sigma0 do no better at this c
    for dd in (0.4, 0.5, 0.6, 0.7):
        r2 = (dd * dd + g * g) / (dd * (D * D + g * g) ** 2)
        assert r2.max() >= ratio.max() - 1e-12
    c1, C8 = E.quartic_kernel_c1(F(7, 8), F(0))
    assert abs(float(c1.mid()) - 96 * math.sqrt(3) / 343) < 1e-15
    assert 0.00304 < float(C8.mid()) < 0.00306


