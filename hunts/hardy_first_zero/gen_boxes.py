"""Emit `lean/HardyFirstZero/Boxes.lean`: the term-box tables at the two endpoints.

Run from the repository root:

    .venv/bin/python hunts/hardy_first_zero/gen_boxes.py            # write the Lean file
    .venv/bin/python hunts/hardy_first_zero/gen_boxes.py --check    # compare, write nothing

The boxes are computed by the lab's bit-exact rational mirror of the Lean interval
layer (`scripts/61_rung3_mirror.py`). Nothing here is trusted by the proof: every
literal is checked by the Lean kernel against the Lean definition
(`dirichletTermBox2 ... = tA m := by decide +kernel`), so a wrong mirror value makes
the build fail, never the theorem wrong. The generator also re-runs the final sign
test in exact rational arithmetic before it writes anything, so a table that cannot
decide the sign is refused here rather than discovered in the kernel.
"""
from __future__ import annotations

import argparse
import math
import sys
from fractions import Fraction as F
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
if str(ROOT) not in sys.path:  # pragma: no cover - import bootstrap
    sys.path.insert(0, str(ROOT))

from hunts.hardy_first_zero import sizing as SZ  # noqa: E402

OUT = HERE / "lean" / "HardyFirstZero" / "Boxes.lean"
N = 30
NLOG, NEXP, P, KE = 40, 24, 96, 8
POINTS = {"A": F(1413, 100), "B": F(707, 50)}


def q(x: F) -> str:
    x = F(x)
    if x.denominator == 1:
        return f"({x.numerator} : ℚ)"
    return f"({x.numerator} / {x.denominator} : ℚ)"


def c_const(t: F) -> tuple[F, F]:
    """c_N(s) = N/(s-1) + 1/2 + s/(12N) at s = 1/2 + it, exactly."""
    den = F(1, 4) + t * t
    inv_re, inv_im = F(-1, 2) / den, -t / den
    return (N * inv_re + F(1, 2) + F(1, 2) / (12 * N), N * inv_im + t / (12 * N))


def eps(T: F) -> F:
    """The rational remainder bound of `em30_bound`, rounded up on a 1e-7 grid."""
    exact = ((F(1, 2) + T) * (F(3, 2) + T) * (F(5, 2) + T) * (F(7, 2) + T)
             / (24389 * 5 * F(7, 2) * 720))
    return F(math.ceil(exact * 10**7), 10**7)


def tables():
    M = SZ.load_mirror()
    out = {}
    for name, t in POINTS.items():
        S = M.cexact(F(1, 2), t)
        boxes = {m: M.dirichletTermBox2(NLOG, NEXP, P, m.bit_length(), KE, m, S) for m in range(1, N + 1)}
        out[name] = (t, boxes)
    return M, out


def final_check(M, out) -> F:
    """The upper end of Re(zeta_a conj zeta_b) over the inflated boxes, exactly."""
    Z = {}
    for name, (t, boxes) in out.items():
        acc = M.cexact(0, 0)
        for m in range(N):
            acc = M.cadd(acc, boxes[m] if m >= 1 else M.cexact(0, 0))
        cre, cim = c_const(t)
        Mbox = M.cadd(acc, M.cmul(boxes[N], M.cexact(cre, cim)))
        Z[name] = M.cinflate(Mbox, eps(t))
    za, zb = Z["A"], Z["B"]
    return M.iadd(M.imul(za.re, zb.re), M.imul(za.im, zb.im)).hi


def render(out) -> str:
    lines = [
        "import HardyFirstZero.BoxSupport",
        "",
        "/-!",
        "# The term-box tables at `t = 1413/100` and `t = 707/50` (generated)",
        "",
        "Generated by `hunts/hardy_first_zero/gen_boxes.py` from the lab's bit-exact rational",
        "mirror of the interval layer; do not edit by hand. Every literal is checked by the",
        "kernel against `dirichletTermBox2` itself (`decide +kernel`), so the mirror is not",
        f"trusted. Parameters: `nLog = {NLOG}`, `nExp = {NEXP}`, `p = {P}`, `kE = {KE}`, `kL` the bit",
        "length of `m`.",
        "-/",
        "",
        "open Complex ZetaLean ZetaLean.ComplexInterval",
        "",
        "namespace HardyFirstZero",
        "",
        "set_option maxRecDepth 100000",
        "",
    ]
    for name, (t, boxes) in out.items():
        tq = q(t)
        lines.append(f"/-- Term boxes `m^(-s)` at `s = 1/2 + i · {t}`, `1 ≤ m ≤ {N}`. -/")
        lines.append(f"def t{name} : ℕ → ComplexInterval")
        for m in range(1, N + 1):
            b = boxes[m]
            lines.append(f"  | {m} => lit {q(b.re.lo)} {q(b.re.hi)}")
            lines.append(f"      {q(b.im.lo)} {q(b.im.hi)} (by norm_num) (by norm_num)")
        lines.append("  | _ => ComplexInterval.exact 0 0")
        lines.append("")
        for m in range(1, N + 1):
            kl = m.bit_length()
            lines.append(f"theorem t{name}_eq_{m} :")
            lines.append(f"    dirichletTermBox2 {NLOG} {NEXP} {P} {kl} {KE} {m} (ptBox {tq}) = t{name} {m} := by")
            lines.append("  decide +kernel")
            lines.append("")
            lines.append(f"theorem t{name}_mem_{m} :")
            lines.append(f"    (t{name} {m}).contains ((({m} : ℕ) : ℂ) ^ (-sOf (({tq} : ℚ) : ℝ))) := by")
            lines.append(f"  rw [← t{name}_eq_{m}]")
            lines.append("  exact contains_dirichletTermBox2 (by norm_num) (by norm_num) (by norm_num)")
            lines.append("    (ptBox_contains _) (by norm_num) (by norm_num) (by decide +kernel)")
            lines.append("")
        lines.append(f"theorem t{name}_mem : ∀ m < {N + 1},")
        lines.append(f"    (t{name} m).contains ((m : ℂ) ^ (-sOf (({tq} : ℚ) : ℝ))) := by")
        lines.append("  intro m hm")
        lines.append("  interval_cases m")
        lines.append("  · rw [Nat.cast_zero, zero_cpow (neg_ne_zero.mpr (sOf_ne_zero _))]")
        lines.append("    exact contains_zero")
        for m in range(1, N + 1):
            lines.append(f"  · exact t{name}_mem_{m}")
        lines.append("")
        cre, cim = c_const(t)
        lines.append(f"/-- `c_30(s)` at `s = 1/2 + i · {t}`, exactly. -/")
        lines.append(f"def c{name} : ComplexInterval := ComplexInterval.exact {q(cre)} {q(cim)}")
        lines.append("")
        lines.append(f"/-- The remainder bound at `t = {t}`, rounded up. -/")
        lines.append(f"def eps{name} : ℚ := {q(eps(t))}")
        lines.append("")
    lines.append("end HardyFirstZero")
    lines.append("")
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="compare with the file on disk, write nothing")
    args = ap.parse_args(argv)
    M, out = tables()
    hi = final_check(M, out)
    print(f"upper end of Re(zeta_a conj zeta_b) over the boxes: {float(hi):.6e}")
    if not hi < 0:
        print("REFUSED: the boxes do not decide the sign", file=sys.stderr)
        return 1
    text = render(out)
    if args.check:
        same = OUT.is_file() and OUT.read_text(encoding="utf-8") == text
        print("Boxes.lean matches the generator" if same else "Boxes.lean differs from the generator")
        return 0 if same else 1
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
