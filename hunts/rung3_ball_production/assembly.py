#!/usr/bin/env python3
"""Hunt #145: emit the module that would prove `davenport_heilbronn` from plan v2's sites.

Reads `lean/cert/rung3_plan2.json` alone and writes, under `lean/Rung3Assembly/` here:

* `Assembly.lean`: imports the 215 site roots `C<id>` that `scripts/60 --arith ball
  --shard` names (`scripts/69`'s `module_root`), then
  - `big_<seg>`: `‖DH‖ ≤ M` on each edge of the big square, one `upper_<id>` per piece;
  - `big_frontier`: the same on its frontier;
  - `small_<seg>`: `ε' ≤ ‖DH‖` on each edge of the small square, one cell
    (`DH_lower_on_hcell` / `DH_lower_on_vcell`, through `hcell` / `vcell`) per pair of
    adjacent grid points, the derivative bound from `norm_deriv_DH_le` with `big_frontier`;
  - `small_frontier`, `centre_small` (from `centre_lt_centre`);
  - `dh_zero_located` and `dh_zero_located'` (a zero of `DH` in the closed small square),
    `davenport_heilbronn : davenport_heilbronn_statement`, and `dh_separation_of`, which
    pairs the zero with RH to height 100 taken as a hypothesis.
* `Separation.lean`: `dh_separation_of` applied to hunt #137's
  `RHHeight100.rh_height_hundred`.

Each `beta_<id>` enters through `le_trans (by norm_num) beta_<id>`, so the emitter needs
no β literal: Lean reads β off the site theorem's type, and `norm_num` checks it against
the cell's need `ε' + L·h/2`, which `scripts/60` asserts at generation.

`--stubs DIR` also writes `StubSites.lean`, which declares each site's interface (its
`SI_<id>` or `z_<id>` exactly as `scripts/69` emits them, and its theorem as an `axiom`
with the same statement), so the assembly body can be elaborated before production
exists; `--real ID ...` leaves those sites to their compiled oleans.  A stub is a test
harness and never a proof: `#print axioms` names every stub the result rests on.

    .venv/bin/python hunts/rung3_ball_production/assembly.py            # write the two modules
    .venv/bin/python hunts/rung3_ball_production/assembly.py --check    # exit 1 if stale
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import sys
from fractions import Fraction as F
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
PLAN = ROOT / "lean" / "cert" / "rung3_plan2.json"
OUT = HERE / "lean" / "Rung3Assembly"
BANNER = "/- Generated by hunts/rung3_ball_production/assembly.py from lean/cert/rung3_plan2.json. -/"
HSEG, VSEG = ("bottom", "top"), ("left", "right")


def _scripts69():
    spec = importlib.util.spec_from_file_location("rung3_ball_generate_for_assembly",
                                                  ROOT / "scripts" / "69_rung3_ball_generate.py")
    assert spec is not None and spec.loader is not None
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _cell_requirements(plan: dict) -> dict:
    spec = importlib.util.spec_from_file_location("rung3_generate_for_assembly",
                                                  ROOT / "scripts" / "60_rung3_generate.py")
    assert spec is not None and spec.loader is not None
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.cell_requirements(plan)


def bare(x) -> str:
    x = F(x)
    return str(x.numerator) if x.denominator == 1 else f"{x.numerator}/{x.denominator}"


def q(x) -> str:
    """The form `scripts/69` emits, so stub interfaces match the real ones."""
    x = F(x)
    return f"({x.numerator} : ℚ)" if x.denominator == 1 else f"({x.numerator}/{x.denominator} : ℚ)"


def r(x) -> str:
    return f"({q(x)} : ℝ)"


def sym(c, op: str, w) -> str:
    """`((c ∓ w : ℚ) : ℝ)`, the form `frontier_cover` takes after instantiation."""
    return f"(({bare(c)} {op} {bare(w)} : ℚ) : ℝ)"


class Geometry:
    def __init__(self, plan: dict):
        sm = plan["small"]
        self.cre, self.cim, self.w = F(sm["cre"]), F(sm["cim"]), F(sm["w"])
        self.eps, self.w2 = F(sm["eps"]), F(plan["big"]["w2"])
        self.L, self.M = F(plan["L"]), F(plan["M"])
        self.big = {s: [b for b in plan["big"]["boxes"] if b["segment"] == s]
                    for s in HSEG + VSEG}
        self.grid = {s: [g for g in plan["grid"] if g["segment"] == s] for s in HSEG + VSEG}
        self.need = _cell_requirements(plan)
        self._check()

    def edge(self, seg: str, w) -> tuple[str, str, str, F, F, F]:
        """(lo, hi, fixed) as symbolic Lean reals, and as rationals."""
        c_run, c_fix = (self.cre, self.cim) if seg in HSEG else (self.cim, self.cre)
        op = "-" if seg in ("bottom", "left") else "+"
        fixed = c_fix - w if op == "-" else c_fix + w
        return (sym(c_run, "-", w), sym(c_run, "+", w), sym(c_fix, op, w),
                c_run - w, c_run + w, fixed)

    def _check(self) -> None:
        for seg, boxes in self.big.items():
            _, _, _, lo, hi, fixed = self.edge(seg, self.w2)
            run = ("re_lo", "re_hi") if seg in HSEG else ("im_lo", "im_hi")
            fix = ("im_lo", "im_hi") if seg in HSEG else ("re_lo", "re_hi")
            iv = [(F(b[run[0]]), F(b[run[1]])) for b in boxes]
            assert iv[0][0] == lo and iv[-1][1] == hi, seg
            assert all(a[1] == b[0] for a, b in zip(iv, iv[1:])), seg
            assert all(F(b[fix[0]]) == F(b[fix[1]]) == fixed for b in boxes), seg
        for seg, pts in self.grid.items():
            _, _, _, lo, hi, fixed = self.edge(seg, self.w)
            xs = [F(g["x"]) for g in pts]
            assert xs[0] == lo and xs[-1] == hi and xs == sorted(set(xs)), seg
            assert all(F(g["fixed"]) == fixed for g in pts), seg
        assert self.M / (self.w2 - self.w) <= self.L
        assert self.cre - self.w > F(1, 2)


def sites(plan: dict) -> list[tuple[str, str]]:
    """(id, kind) in `scripts/60`'s order: the centre, the grid, the big boxes."""
    out = [("centre", "centre")]
    out += [(g["id"], "grid") for g in plan["grid"]]
    out += [(b["id"], "big") for b in plan["big"]["boxes"]]
    return out


# --------------------------------------------------------------------------- the body

def _big_edge(G: Geometry, seg: str) -> list[str]:
    lo, hi, fixed, *_ = G.edge(seg, G.w2)
    h = seg in HSEG
    var = "x" if h else "y"
    M = r(G.M)
    point = f"⟨{var}, {fixed}⟩" if h else f"⟨{fixed}, {var}⟩"
    out = [f"theorem big_{seg} : ∀ {var} ∈ Icc {lo} {hi}, ‖DH {point}‖ ≤ {M} := by"]
    of_box = "hseg_of_box" if h else "vseg_of_box"
    fixn = "y" if h else "x"
    run = ("re_lo", "re_hi") if h else ("im_lo", "im_hi")
    fix = "im_lo" if h else "re_lo"
    for i, b in enumerate(G.big[seg]):
        sid = b["id"]
        nn = f"(by norm_num [SI_{sid}])"
        piece = (f"{of_box} (M := {M}) (a := {r(b[run[0]])}) (b := {r(b[run[1]])}) "
                 f"({fixn} := {r(b[fix])}) upper_{sid}\n      {nn} {nn} {nn} {nn}")
        if i == 0:
            out.append(f"  have h0 := {piece}")
        else:
            out.append(f"  have h{i} := icc_merge h{i - 1}\n    ({piece})")
    n = len(G.big[seg]) - 1
    congr = "hseg_congr" if h else "vseg_congr"
    out.append(f"  exact {congr} (P := fun z => ‖DH z‖ ≤ {M}) (by norm_num) (by norm_num) "
               f"(by norm_num) h{n}")
    return out


def _small_edge(G: Geometry, seg: str) -> list[str]:
    lo, hi, fixed, *_ = G.edge(seg, G.w)
    h = seg in HSEG
    var = "x" if h else "y"
    eps = r(G.eps)
    point = f"⟨{var}, {fixed}⟩" if h else f"⟨{fixed}, {var}⟩"
    out = [f"theorem small_{seg} : ∀ {var} ∈ Icc {lo} {hi}, {eps} ≤ ‖DH {point}‖ := by",
           "  have hD := deriv_bound_small"]
    cell, fixn = ("hcell", "y") if h else ("vcell", "x")
    pts = G.grid[seg]
    for i in range(len(pts) - 1):
        a, b = pts[i], pts[i + 1]
        assert F(a["gap_next"]) == F(b["x"]) - F(a["x"])
        assert G.need[a["id"]] >= G.eps + G.L * F(a["gap_next"]) / 2
        c = (f"{cell} (ε := {eps}) (by norm_num) hD (p := {r(a['x'])}) (q := {r(b['x'])}) "
             f"({fixn} := {r(a['fixed'])})\n      (by norm_num) (by norm_num) (by norm_num) "
             f"⟨by norm_num, by norm_num⟩\n      (le_trans (by norm_num) beta_{a['id']}) "
             f"(le_trans (by norm_num) beta_{b['id']})")
        out.append(f"  have h0 := {c}" if i == 0 else
                   f"  have h{i} := icc_merge h{i - 1}\n    ({c})")
    congr = "hseg_congr" if h else "vseg_congr"
    out.append(f"  exact {congr} (P := fun z => {eps} ≤ ‖DH z‖) (by norm_num) (by norm_num) "
               f"(by norm_num) h{len(pts) - 2}")
    return out


def body(plan: dict) -> str:
    G = Geometry(plan)
    cre, cim, w, w2, eps = (bare(G.cre), bare(G.cim), bare(G.w), bare(G.w2), bare(G.eps))
    M, L = r(G.M), r(G.L)
    a: list[str] = []
    add = a.extend
    add(["", "open Complex Set ZetaLean ZetaLean.DH ZetaLean.DH.Cert ZetaLean.DH.Rung3Assembly", "",
         "set_option maxHeartbeats 4000000", "",
         "namespace ZetaLean.DH.Rung3Assembly.Plan2", "",
         f"/-! Plan v2: centre {cre} + {cim}·i, small half-width {w}, eps' {eps},",
         f"big half-width {w2}, M = {bare(G.M)}, L = {bare(G.L)}. -/", ""])
    for seg in HSEG + VSEG:
        add(_big_edge(G, seg) + [""])
    add([f"theorem big_frontier : ∀ z ∈ frontier (dhSquare ({cre}) ({cim}) ({w2})), ‖DH z‖ ≤ {M} :=",
         "  frontier_cover (by norm_num) big_bottom big_top big_left big_right", "",
         "theorem deriv_bound_small : ∀ z : ℂ,",
         f"    z.re ∈ Icc {sym(G.cre, '-', G.w)} {sym(G.cre, '+', G.w)} →",
         f"    z.im ∈ Icc {sym(G.cim, '-', G.w)} {sym(G.cim, '+', G.w)} → ‖deriv DH z‖ ≤ {L} :=",
         f"  deriv_bound (by norm_num) (by norm_num) big_frontier (by norm_num)", ""])
    for seg in HSEG + VSEG:
        add(_small_edge(G, seg) + [""])
    re_lo, re_hi = sym(G.cre, "-", G.w), sym(G.cre, "+", G.w)
    im_lo, im_hi = sym(G.cim, "-", G.w), sym(G.cim, "+", G.w)
    add([f"theorem small_frontier : ∀ z ∈ frontier (dhSquare ({cre}) ({cim}) ({w})), {r(G.eps)} ≤ ‖DH z‖ :=",
         "  frontier_cover (by norm_num) small_bottom small_top small_left small_right", "",
         f"theorem centre_small : ‖DH ⟨{r(G.cre)}, {r(G.cim)}⟩‖ < {r(G.eps)} := by",
         "  simpa only [z_centre] using centre_lt_centre", "",
         "/-- A zero of `DH` in the closed small square of plan v2. -/",
         "theorem dh_zero_located : ∃ z : ℂ, DH z = 0 ∧",
         f"    z.re ∈ Icc {re_lo} {re_hi} ∧ z.im ∈ Icc {im_lo} {im_hi} :=",
         f"  dh_zero_of_square (cre := {cre}) (cim := {cim}) (w := {w}) (ε' := {eps})",
         "    (by norm_num) centre_small small_frontier", "",
         "/-- The same zero, as a bound on its real part and its distance from the centre's height. -/",
         "theorem dh_zero_located' : ∃ z : ℂ, DH z = 0 ∧",
         f"    {r(G.cre - G.w)} ≤ z.re ∧ |z.im - {r(G.cim)}| ≤ {r(G.w)} := by",
         "  obtain ⟨z, hz, hre, him⟩ := dh_zero_located",
         "  obtain ⟨h1, -⟩ := hre",
         "  obtain ⟨h3, h4⟩ := him",
         "  push_cast at h1 h3 h4 ⊢",
         "  refine ⟨z, hz, by linarith, abs_le.mpr ⟨by linarith, by linarith⟩⟩", "",
         "theorem davenport_heilbronn : davenport_heilbronn_statement :=",
         f"  dh_statement_of_square (cre := {cre}) (cim := {cim}) (w := {w}) (ε' := {eps})",
         "    (by norm_num) (by norm_num) centre_small small_frontier", "",
         "/-- The zero beside RH to height 100 for Mathlib's `riemannZeta`, taken as the body",
         "of hunt #137's `RHUpToHeight 100`; `Separation.lean` discharges it. -/",
         "theorem dh_separation_of",
         "    (hRH : ∀ ρ : ℂ, riemannZeta ρ = 0 → 0 < ρ.re → ρ.re < 1 → 0 < ρ.im → ρ.im ≤ 100 →",
         "      ρ.re = 1 / 2 ∧ analyticOrderAt riemannZeta ρ = 1) :",
         "    (∃ s : ℂ, DH s = 0 ∧ 0 < s.re ∧ s.re < 1 ∧ 0 < s.im ∧ s.im ≤ 100 ∧ s.re ≠ 1 / 2) ∧",
         "      ∀ ρ : ℂ, riemannZeta ρ = 0 → 0 < ρ.re → ρ.re < 1 → 0 < ρ.im → ρ.im ≤ 100 →",
         "        ρ.re = 1 / 2 := by",
         "  obtain ⟨z, hz, ⟨h1, h2⟩, ⟨h3, h4⟩⟩ := dh_zero_located",
         "  push_cast at h1 h2 h3 h4",
         "  exact separation_of hRH hz (by linarith) (by linarith)",
         "    (fun h => by rw [h] at h1; norm_num at h1) (by linarith) (by linarith)", "",
         "end ZetaLean.DH.Rung3Assembly.Plan2", ""])
    return "\n".join(a)


def assembly(plan: dict) -> str:
    s69 = _scripts69()
    roots = [s69.module_root(sid) for sid, _ in sites(plan)]
    assert len(roots) == len(set(roots)) == 215
    head = [BANNER, "import Rung3Assembly.Support"] + [f"import {m}" for m in roots]
    return "\n".join(head) + "\n" + body(plan)


def separation() -> str:
    return "\n".join([
        BANNER, "import Rung3Assembly.Assembly", "import RHHeight100.Main100", "",
        "open ZetaLean.DH", "",
        "namespace ZetaLean.DH.Rung3Assembly.Plan2", "",
        "/-- `DH` has a zero off the critical line below height 100; Mathlib's `riemannZeta`",
        "has none there (hunt #137). -/",
        "theorem dh_separation_hundred :",
        "    (∃ s : ℂ, DH s = 0 ∧ 0 < s.re ∧ s.re < 1 ∧ 0 < s.im ∧ s.im ≤ 100 ∧ s.re ≠ 1 / 2) ∧",
        "      ∀ ρ : ℂ, riemannZeta ρ = 0 → 0 < ρ.re → ρ.re < 1 → 0 < ρ.im → ρ.im ≤ 100 →",
        "        ρ.re = 1 / 2 :=",
        "  dh_separation_of RHHeight100.rh_height_hundred", "",
        "end ZetaLean.DH.Rung3Assembly.Plan2", ""])


def stubs(plan: dict, real: set[str]) -> str:
    """Each site's interface as `scripts/69` emits it, its theorem as an axiom."""
    need = _cell_requirements(plan)
    a = ["/- Test harness from hunts/rung3_ball_production/assembly.py: site interfaces with",
         "   their theorems as axioms. Not a proof of anything. -/",
         "import ZetaLean.BallCertSupport"] + [f"import C{sid}" for sid in sorted(real)]
    a += ["", "open Complex ZetaLean ZetaLean.DH", "", "namespace ZetaLean.DH.Cert", ""]
    sm = plan["small"]
    for sid, kind in sites(plan):
        if sid in real:
            continue
        if kind == "big":
            b = next(x for x in plan["big"]["boxes"] if x["id"] == sid)
            a += [f"def SI_{sid} : ComplexInterval :=",
                  f"  ⟨⟨{q(b['re_lo'])}, {q(b['re_hi'])}, by norm_num⟩, "
                  f"⟨{q(b['im_lo'])}, {q(b['im_hi'])}, by norm_num⟩⟩",
                  f"axiom upper_{sid} {{s : ℂ}} (hS : SI_{sid}.contains s) :",
                  f"    ‖DH s‖ ≤ (({q(plan['M'])}) : ℝ)", ""]
        elif kind == "grid":
            g = next(x for x in plan["grid"] if x["id"] == sid)
            px, py = (g["x"], g["fixed"]) if g["segment"] in HSEG else (g["fixed"], g["x"])
            a += [f"noncomputable def z_{sid} : ℂ := ⟨(({q(px)}) : ℝ), (({q(py)}) : ℝ)⟩",
                  f"axiom beta_{sid} : (({q(need[sid])}) : ℝ) ≤ ‖DH z_{sid}‖", ""]
        else:
            a += [f"noncomputable def z_{sid} : ℂ := ⟨(({q(sm['cre'])}) : ℝ), (({q(sm['cim'])}) : ℝ)⟩",
                  f"axiom centre_lt_{sid} : ‖DH z_{sid}‖ < (({q(sm['eps'])}) : ℝ)", ""]
    a += ["end ZetaLean.DH.Cert", ""]
    return "\n".join(a)


def harness(plan: dict) -> str:
    """The assembly body under the stub imports, with its axioms printed."""
    return ("\n".join([BANNER, "import Rung3Assembly.Support", "import StubSites"])
            + "\n" + body(plan) + "\n#print axioms ZetaLean.DH.Rung3Assembly.Plan2.davenport_heilbronn\n"
            + "#print axioms ZetaLean.DH.Rung3Assembly.Plan2.dh_zero_located'\n"
            + "#print axioms ZetaLean.DH.Rung3Assembly.Plan2.dh_separation_of\n")


def emitted(plan: dict) -> dict[str, str]:
    return {"Assembly.lean": assembly(plan), "Separation.lean": separation()}


def record(log: str, real: list[str], plan: dict) -> dict:
    """What a harness compile printed: its exit, `/usr/bin/time` line and axioms."""
    import re
    rc = int(re.search(r"^rc=(\d+)$", log, re.M).group(1))
    t = re.search(r"([\d.]+)\+([\d.]+)_cpu_([\d.]+)_wall_(\d+)_kb", log)
    out = {"date": "2026-10-26", "real_sites": real, "returncode": rc,
           "errors": len(re.findall(r": error", log)),
           "cpu_s": round(float(t.group(1)) + float(t.group(2)), 2),
           "wall_s": float(t.group(3)), "maxrss_kb": int(t.group(4)), "axioms": {}}
    for name, ax in re.findall(r"'([\w.']+)' depends on axioms: \[(.*?)\]", log, re.S):
        out["axioms"][name.rsplit(".", 1)[-1]] = sorted(a.strip() for a in ax.split(","))
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--stubs", type=Path, help="also write StubSites.lean and Harness.lean here")
    ap.add_argument("--real", nargs="*", default=[], help="site ids left to compiled oleans")
    ap.add_argument("--record", type=Path, help="write a harness log's outcome into pilot.json")
    args = ap.parse_args()
    plan = json.loads(PLAN.read_text())
    stale = []
    for name, text in emitted(plan).items():
        path = OUT / name
        if args.check:
            if not path.is_file() or path.read_text() != text:
                stale.append(name)
            continue
        path.write_text(text)
        print(f"wrote {path.relative_to(ROOT)} sha256={hashlib.sha256(text.encode()).hexdigest()[:16]}")
    if args.stubs:
        args.stubs.mkdir(parents=True, exist_ok=True)
        (args.stubs / "StubSites.lean").write_text(stubs(plan, set(args.real)))
        (args.stubs / "Harness.lean").write_text(harness(plan))
        print(f"wrote StubSites.lean and Harness.lean in {args.stubs}")
    if args.record:
        pj = HERE / "pilot.json"
        pilot = json.loads(pj.read_text())
        pilot["assembly_harness"] = record(args.record.read_text(), args.real, plan)
        pj.write_text(json.dumps(pilot, indent=1) + "\n")
        print(json.dumps({k: v for k, v in pilot["assembly_harness"].items() if k != "axioms"}))
    if stale:
        sys.exit(f"stale: {stale}")


if __name__ == "__main__":
    main()
