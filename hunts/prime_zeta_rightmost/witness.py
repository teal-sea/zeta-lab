def prime_zeta_acb(s: acb, K: int, mu, sigma_lo: Fraction) -> acb:
    """Ball enclosure of P(s) for Re s >= sigma_lo > 1: Moebius series plus
    the tail ball of instrument.py docstring 1 (monotone in sigma, so the
    exact lower endpoint sigma_lo of Re s gives a valid bound)."""
    total = acb(0)
    for k in range(1, K + 1):
        if mu[k] == 0:
            continue
        total += (acb(mu[k]) / k) * (k * s).zeta().log()
    sl = arb_from_fraction(sigma_lo)
    T = 3 * arb(2) ** (-(arb(K + 1) * sl)) / ((K + 1) * (1 - arb(2) ** (-sl)))
    ball = T.union(-T)
    return total + acb(ball, ball)


def winding_count(center: complex, half_w: Fraction, c_shift: acb, K: int, mu,
                  m_per_edge: int = 24, max_refine: int = 3) -> dict:
    """Decided winding number of P(s) - c_shift around the square
    center +/- half_w, or an honest failure record. Exact-rational endpoint
    bookkeeping throughout; pi enters via the exact endpoints of arb.pi()."""
    cx = Fraction(center.real).limit_denominator(10 ** 12)
    cy = Fraction(center.imag).limit_denominator(10 ** 12)
    sigma_lo = cx - half_w
    pi_lo, pi_hi = arb_endpoints(arb.pi())
    for attempt in range(max_refine + 1):
        M = m_per_edge * (2 ** attempt)
        pts = []
        for j in range(M):
            f = Fraction(j, M)
            pts.append((cx - half_w + 2 * half_w * f, cy - half_w))
        for j in range(M):
            f = Fraction(j, M)
            pts.append((cx + half_w, cy - half_w + 2 * half_w * f))
        for j in range(M):
            f = Fraction(j, M)
            pts.append((cx + half_w - 2 * half_w * f, cy + half_w))
        for j in range(M):
            f = Fraction(j, M)
            pts.append((cx - half_w, cy + half_w - 2 * half_w * f))
        vals = []
        ok = True
        for (x, y) in pts:
            v = prime_zeta_acb(acb(arb_from_fraction(x), arb_from_fraction(y)),
                               K, mu, sigma_lo) - c_shift
            if not bool(v.abs_lower() > 0):
                ok = False
                break
            vals.append(v)
        if not ok:
            continue
        tot_lo = Fraction(0)
        tot_hi = Fraction(0)
        ok = True
        for j in range(len(vals)):
            th = (vals[(j + 1) % len(vals)] / vals[j]).arg()
            th_lo, th_hi = arb_endpoints(th)
            if not (-pi_lo < th_lo and th_hi < pi_lo):
                ok = False
                break
            tot_lo += th_lo
            tot_hi += th_hi
        if not ok:
            continue
        cands = [tot_lo / (2 * pi_lo), tot_lo / (2 * pi_hi),
                 tot_hi / (2 * pi_lo), tot_hi / (2 * pi_hi)]
        w_lo, w_hi = min(cands), max(cands)
        n_lo, n_hi = ceil(w_lo), floor(w_hi)
        if n_lo == n_hi:
            return {"decided": True, "winding": int(n_lo),
                    "boundary_points": len(vals), "attempts": attempt + 1}
        return {"decided": False,
                "reason": "winding enclosure contains more than one integer",
                "enclosure": [float(w_lo), float(w_hi)],
                "boundary_points": len(vals)}
    return {"decided": False,
            "reason": "a boundary ball contained 0 or an argument increment "
                      "could not be kept inside (-pi, pi) at the refinement cap"}


def box_counter_controls(screen) -> dict:
    """Exercise the counter unconditionally: a null box (expect winding 0)
    and a planted zero of P - c (expect winding 1)."""
    saved = fctx.prec
    fctx.prec = 192
    K = 25
    mu = mobius_sieve(K + 1)
    out = {"backend": "python-flint (acb)", "precision": "192 bits",
           "moebius_K": K}
    try:
        t_null = screen["argmax_for_null_box"]["t"]
        with Timer() as tm:
            r0 = winding_count(complex(SIGMA1_F, t_null), Fraction(1, 100),
                               acb(0), K, mu)
        out["null_box"] = {
            "center": [SIGMA1_F, t_null], "half_width": "1/100",
            "expected_winding": 0, "result": r0, "time_s": round(tm.seconds, 1),
            "note": "center chosen at the coarse-grid |F| maximum, far from "
                    "any zero of P",
        }
        sc = complex(SIGMA1_F, t_null + 0.5)
        cxy = acb(arb_from_fraction(Fraction(sc.real).limit_denominator(10 ** 12)),
                  arb_from_fraction(Fraction(sc.imag).limit_denominator(10 ** 12)))
        val = prime_zeta_acb(cxy, K, mu, Fraction(sc.real).limit_denominator(10 ** 12) - Fraction(1, 100))
        c_mid = acb(val.real.mid(), val.imag.mid())
        with Timer() as tm:
            r1 = winding_count(sc, Fraction(1, 100), c_mid, K, mu)
        out["planted_zero_box"] = {
            "center": [sc.real, sc.imag], "half_width": "1/100",
            "expected_winding": 1, "result": r1, "time_s": round(tm.seconds, 1),
            "note": "c is the exact dyadic midpoint of the ball P(center), so "
                    "P - c has a zero within the ball radius of the center by "
                    "construction; a decided winding 1 validates the counter",
        }
        out["both_controls_pass"] = bool(
            r0.get("decided") and r0.get("winding") == 0
            and r1.get("decided") and r1.get("winding") == 1)
    finally:
        fctx.prec = saved
    return out


