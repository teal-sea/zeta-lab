def polish_and_decide(t_best: float, decided_consts: dict) -> dict:
    out = {"ran": True}
    mp.dps = 40
    try:
        s0 = mp.findroot(lambda s: mp.primezeta(s), mp.mpc(SIGMA1_F, t_best),
                         solver="muller", tol=1e-30)
    except Exception as e:  # noqa: BLE001
        out["converged"] = False
        out["error"] = str(e)
        return out
    resid = abs(mp.primezeta(s0))
    out["converged"] = True
    out["s0"] = [mp.nstr(s0.real, 25), mp.nstr(s0.imag, 25)]
    out["residual"] = float(resid)
    out["polish"] = "mpmath findroot (muller) on mpmath.primezeta, dps 40; measured"
    xs_hi = fr_from_decimal(decided_consts["x_star"]["flint"]["interval"][1])
    sc_lo = fr_from_decimal(decided_consts["sigma_c"]["flint"]["interval"][0])
    re0 = Fraction(float(s0.real)).limit_denominator(10 ** 15)
    half_w = Fraction(1, 1000)
    in_window = xs_hi < re0 - half_w and re0 + half_w < sc_lo
    out["box_strictly_inside_window_decided"] = bool(in_window)
    if not in_window or resid > 1e-25:
        out["witness_decided"] = False
        return out
    saved = fctx.prec
    fctx.prec = 256
    K = 40
    mu = mobius_sieve(K + 1)
    try:
        r = winding_count(complex(float(s0.real), float(s0.imag)), half_w,
                          acb(0), K, mu)
    finally:
        fctx.prec = saved
    out["box_count"] = r
    out["witness_decided"] = bool(r.get("decided") and r.get("winding", 0) >= 1)
    return out


