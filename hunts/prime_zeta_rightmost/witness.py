def window_products(m_odd_head: np.ndarray, primes_odd_head: np.ndarray, eps0: float):
    rows = []
    full_prod = 1.0
    constrained = []
    for p, m in zip(primes_odd_head, m_odd_head):
        if eps0 < 2 * m:
            th = acos(1 - eps0 / m)
            frac = th / pi
            full_prod *= frac
            constrained.append((int(p), float(m)))
            rows.append({"p": int(p), "m_p": float(m),
                         "theta_max_rad": round(th, 4),
                         "window_fraction": round(frac, 4)})
        else:
            rows.append({"p": int(p), "m_p": float(m),
                         "theta_max_rad": None, "window_fraction": 1.0,
                         "note": "individually unconstrained, eps0 >= 2 m_p"})
    n_c = len(constrained)
    eq_prod = 1.0
    for p, m in constrained:
        arg = 1 - eps0 / (n_c * m)
        th = acos(max(-1.0, arg))
        eq_prod *= th / pi
    return rows, full_prod, eq_prod, n_c


def solve_theta(mvec: np.ndarray, eps: float) -> float:
    def mean_loss(theta):
        k = theta * mvec
        r = np.where(k > 0, sp.i1e(k) / sp.i0e(k), 0.0)
        return float(np.sum(mvec * (1.0 - r)))
    lo, hi = 0.0, 1.0
    while mean_loss(hi) > eps:
        hi *= 2.0
        if hi > 1e12:
            break
    for _ in range(200):
        mid = 0.5 * (lo + hi)
        if mean_loss(mid) > eps:
            lo = mid
        else:
            hi = mid
    return 0.5 * (lo + hi)


def chernoff_log10(mvec: np.ndarray, eps: float, theta: float) -> float:
    k = theta * mvec
    return (theta * eps + float(np.sum(np.log(sp.i0e(k))))) / log(10.0)


def coherence_prob_tilted(mvec: np.ndarray, eps: float, n_samples: int,
                          rng: np.random.Generator, batch: int = IS_BATCH):
    theta = solve_theta(mvec, eps)
    kap = theta * mvec
    log_m_theta = float(np.sum(np.log(sp.i0e(kap))))
    total_w = 0.0
    total_w2 = 0.0
    n_done = 0
    n_hits = 0
    while n_done < n_samples:
        b = min(batch, n_samples - n_done)
        phi = rng.vonmises(0.0, kap, size=(b, mvec.size))
        L = ((1.0 - np.cos(phi)) * mvec).sum(axis=1)
        w = np.where(L <= eps, np.exp(theta * (L - eps)), 0.0)
        total_w += float(w.sum())
        total_w2 += float((w * w).sum())
        n_hits += int(np.count_nonzero(w))
        n_done += b
    mean_w = total_w / n_done
    var_w = max(0.0, total_w2 / n_done - mean_w ** 2)
    stderr_w = sqrt(var_w / n_done)
    scale = log_m_theta + theta * eps          # log of M(theta) e^{theta eps}
    prob = mean_w * np.exp(scale)
    stderr = stderr_w * np.exp(scale)
    return {
        "prob": float(prob),
        "stderr": float(stderr),
        "theta": float(theta),
        "n_samples": int(n_done),
        "hit_fraction_tilted": n_hits / n_done,
        "chernoff_upper_log10": chernoff_log10(mvec, eps, theta),
    }


def coherence_prob_plain(mvec: np.ndarray, eps: float, n_samples: int,
                         rng: np.random.Generator, batch: int = 200_000):
    hits = 0
    n_done = 0
    while n_done < n_samples:
        b = min(batch, n_samples - n_done)
        phi = rng.uniform(-pi, pi, size=(b, mvec.size))
        L = ((1.0 - np.cos(phi)) * mvec).sum(axis=1)
        hits += int(np.count_nonzero(L <= eps))
        n_done += b
    p = hits / n_done
    return {"prob": p, "stderr": sqrt(max(p * (1 - p), 1e-300) / n_done),
            "n_samples": n_done, "hits": hits}


