"""WP6, the bonus witness hunt: look for an explicit zero of the prime zeta
function P(s) = sum_p p^(-s) with Re s in (x_star, sigma_c) ~ (1.7287, 1.7795),
along the line sigma_1 = 7/4. Budget capped; the pre-registered prediction P4
expects absence below t = 10^8, and absence changes nothing.

Run from the repo root:

    .venv/bin/python hunts/prime_zeta_rightmost/witness.py

Writes witness_results.json next to this file. Vocabulary contract: decided
means an interval or ball enclosure whose exact endpoints settle a sign,
stated with backend and precision; measured means a float route; heuristic
means an order-of-magnitude model with measured inputs, and is never more
than that. Only the box counter at the bottom can decide a witness, and it
only runs if the screen produces a candidate.

Stage 1, margin analysis (decided, flint 350 bits, iv cross-check).
  At s = sigma_1 + i t the p = 2 term has modulus r_2 = 2^(-sigma_1) and the
  rest of the series has total modulus R = P(sigma_1) - r_2. A zero needs the
  p >= 3 part to land exactly on -2^(-s), so its resultant must shrink from
  the fully aligned maximum R down to r_2. The coherence budget is

      eps_0 = R - r_2 = h(sigma_1) = P(sigma_1) - 2^(1 - sigma_1),

  the same h whose root is sigma_c. With head cutoff X = 50 and prime tail
  T_X = sum_{p > X} p^(-sigma_1), the head budget is identical:
  (head max) - (r_2 - T_X) = (R - T_X) - r_2 + T_X = eps_0 exactly.

Stage 2, required alignment quality and expected t (heuristic).
  Write the loss of the p-term at phase deviation phi_p from perfect
  alignment as l_p = m_p (1 - cos phi_p), m_p = p^(-sigma_1). A zero on the
  line needs total loss exactly eps_0; anywhere in the strip up to sigma_c it
  needs loss <= eps_0 (extra alignment moves the balancing sigma to the
  right, up to sigma_c). Three estimates of the density of such t, using
  Weyl equidistribution of (t log p / 2pi mod 1) on the torus (the log p are
  linearly independent over Q):

  a. Kronecker product of windows. Each single prime must individually obey
     m_p (1 - cos phi_p) <= eps_0, a necessary condition giving a window
     |phi_p| <= arccos(1 - eps_0 / m_p) when eps_0 < 2 m_p. The product of
     window fractions is an upper bound for the density of coherent t (the
     conditions are jointly necessary and the phases are equidistributed
     jointly), hence a lower bound for the expected first t. The equal-share
     variant splits the budget evenly over the constrained primes, which
     maximizes the product of window widths under sum of budgets = eps_0,
     and serves as an optimistic point estimate that ignores every prime
     outside the constrained set.
  b. Chernoff bound. E[exp(-theta l_p)] = exp(-theta m_p) I0(theta m_p)
     = i0e(theta m_p), so Prob(L <= eps) <= exp(theta eps) prod_p
     i0e(theta m_p) for every theta > 0; minimized near the theta that makes
     the tilted mean equal eps. Deterministic, and an upper bound within the
     equidistribution model.
  c. Tilted Monte Carlo. Under exponential tilting the phase of the p-term
     is von Mises with concentration kappa_p = theta m_p, so sampling
     phi_p ~ VonMises(0, kappa_p) and weighting by
     M(theta) exp(theta L) 1{L <= eps}, with M(theta) = prod_p i0e(kappa_p),
     gives an unbiased estimate of Prob(L <= eps). The sampler is checked
     against plain uniform Monte Carlo at a relaxed budget where plain MC
     can see the event.

  The loss model uses the odd primes p <= 1000; the primes beyond 1000 carry
  total modulus tail_1000, so the model brackets the truth between budget
  eps_0 (those primes maximally helpful) and eps_0 - 2 tail_1000 (maximally
  hostile). Expected first t: coherent moments arrive with density
  Prob(L <= eps); while coherent, the resultant direction and the target
  direction -arg(2^(-it)) drift at relative angular speed nu_rel =
  |nu_odd - log 2| (nu_odd the modulus-weighted mean of log p over the odd
  head), so zeros arrive at rate about Prob * nu_rel / 2pi per unit t and

      t_expected ~ 2 pi / (nu_rel * Prob(L <= eps)).

  Order of magnitude only: it treats coherence and direction as independent
  and ignores the duration of coherent excursions.

Stage 3, the screen (measured, numpy float64).
  |F(sigma_1 + i t)| for F the head over primes p <= 47, on the uniform grid
  t in [0, 10^8] with step = (2 pi / nu_bar) / 8, where nu_bar is the
  modulus-weighted mean oscillation frequency sum m_p log p / sum m_p (the
  mean oscillation scale of the task brief). Phases are generated by the
  exact-grid recurrence exp(-i (t0 + j dt) log p) =
  exp(-i t0 log p) exp(-i j dt log p), with the per-chunk array reused, and
  spot-checked against direct evaluation. ||P| - |F|| <= T_50 pointwise.
  Refinement pass A re-evaluates the best coarse windows with primes
  <= 10^4, pass B with primes <= 10^6; beyond 10^6 the prime tail is below
  the all-integer bound (10^6)^(-3/4) / (3/4) + (10^6)^(-7/4) < 4.22e-5.
  The line screen is only sensitive to zeros within roughly 0.01 of
  sigma_1 in the real direction (typical |P'| is a few tenths).

Stage 4, candidate gate (runs only if pass B finds |P| < 1e-4).
  Polish by mpmath findroot (muller) on mpmath.primezeta from the best
  point; a polished root counts as a witness only if a small box around it,
  strictly inside (x_star, sigma_c) by exact comparison against the decided
  intervals of decide.py, gets a decided winding number >= 1 from the
  argument-principle counter below.

The box counter (decided when it reports so, python-flint acb).
  P is enclosed on balls by the Moebius series sum_{k<=K} mu(k)/k
  log zeta(k s) plus the tail ball |sum_{k>K}| <= 3 * 2^(-(K+1) sigma_lo)
  / ((K+1)(1 - 2^(-sigma_lo))) with sigma_lo the exact lower endpoint of
  Re s (the bound of instrument.py docstring 1, monotone in sigma). The
  winding number of P - c around a rectangle is the sum of the argument
  increments arg(v_{j+1} / v_j) over a boundary sampling: if every boundary
  ball excludes 0 and every increment enclosure stays strictly inside
  (-pi, pi), the total is 2 pi times the winding number, and the integer is
  decided when the exact-endpoint enclosure of total / 2 pi contains exactly
  one integer. All comparisons are exact rational endpoint comparisons; pi
  enters only through the exact endpoints of the arb.pi ball. Two controls
  run unconditionally: a null box far from any zero (winding 0) and a
  shifted function P - c with a zero planted inside by construction
  (winding 1), so the gated tool is exercised even when no candidate exists.
"""

