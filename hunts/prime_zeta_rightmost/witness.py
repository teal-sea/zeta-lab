def coarse_screen(primes_head: np.ndarray, step: float):
    logp = np.log(primes_head.astype(float))
    mvec = primes_head.astype(float) ** (-SIGMA1_F)
    n_points = int(floor(T_MAX / step)) + 1
    chunk = 1 << 19
    n_chunks = (n_points + chunk - 1) // chunk
    E = [np.exp(-1j * lp * step * np.arange(chunk)) for lp in logp]
    chunk_min = np.empty(n_chunks)
    chunk_argt = np.empty(n_chunks)
    thresholds = [0.05, 0.02, 0.01, 0.005, 0.002, 0.001]
    counts = {str(th): 0 for th in thresholds}
    gmax_val, gmax_t = -1.0, 0.0
    with Timer() as tm:
        for c in range(n_chunks):
            i0 = c * chunk
            n = min(chunk, n_points - i0)
            t0 = i0 * step
            S = np.zeros(n, dtype=complex)
            for lp, m, Ep in zip(logp, mvec, E):
                S += (m * np.exp(-1j * lp * t0)) * Ep[:n]
            a = np.abs(S)
            j = int(np.argmin(a))
            chunk_min[c] = a[j]
            chunk_argt[c] = t0 + j * step
            for th in thresholds:
                counts[str(th)] += int(np.count_nonzero(a < th))
            if c == 0:
                tloc = np.arange(n) * step
                jmask = (tloc >= 10.0) & (tloc <= 100.0)
                jj = int(np.argmax(np.where(jmask, a, -1.0)))
                gmax_val, gmax_t = float(a[jj]), t0 + jj * step
    # spot-check the phase recurrence against direct evaluation
    rng = np.random.default_rng(7)
    dev = 0.0
    for idx in rng.integers(0, n_points, size=8):
        t = float(idx) * step
        direct = np.abs(np.sum(mvec * np.exp(-1j * t * logp)))
        c, j = int(idx) // chunk, int(idx) % chunk
        t0 = c * chunk * step
        rec = np.abs(sum((m * np.exp(-1j * lp * t0)) * np.exp(-1j * lp * step * j)
                         for lp, m in zip(logp, mvec)))
        dev = max(dev, abs(float(direct) - float(rec)))
    order = np.argsort(chunk_min)
    return {
        "n_points": n_points,
        "n_chunks": n_chunks,
        "chunk": chunk,
        "time_s": round(tm.seconds, 1),
        "counts_below": counts,
        "recurrence_vs_direct_max_dev": float(dev),
        "chunk_min": chunk_min,
        "chunk_argt": chunk_argt,
        "order": order,
        "argmax_for_null_box": {"t": gmax_t, "absF": gmax_val},
    }


def eval_head(ts: np.ndarray, primes: np.ndarray) -> np.ndarray:
    logp = np.log(primes.astype(float))
    mvec = primes.astype(float) ** (-SIGMA1_F)
    S = np.zeros(ts.size, dtype=complex)
    block = 10_000
    for b0 in range(0, primes.size, block):
        lp = logp[b0:b0 + block]
        mm = mvec[b0:b0 + block]
        S += (mm * np.exp(-1j * np.outer(ts, lp))).sum(axis=1)
    return np.abs(S)


def refine(screen, step: float):
    p1e4 = np_primes_upto(10_000)
    p1e6 = np_primes_upto(1_000_000)
    rem6 = (1e6) ** (-0.75) / 0.75 + (1e6) ** (-1.75)
    # pass A: best 40 coarse windows, primes <= 1e4
    top = screen["order"][:40]
    bestA = []
    with Timer() as tA:
        for c in top:
            tc = screen["chunk_argt"][c]
            ts = tc + np.linspace(-step, step, 257)
            ts = ts[ts >= 0]
            a = eval_head(ts, p1e4)
            j = int(np.argmin(a))
            bestA.append((float(a[j]), float(ts[j])))
    bestA.sort()
    # pass B: best 10 refined points, primes <= 1e6
    bestB = []
    with Timer() as tB:
        for val, tc in bestA[:10]:
            ts = tc + np.linspace(-step / 128, step / 128, 257)
            ts = ts[ts >= 0]
            a = eval_head(ts, p1e6)
            j = int(np.argmin(a))
            bestB.append((float(a[j]), float(ts[j])))
    bestB.sort()
    return {
        "passA": {"windows": 40, "primes_upto": 10_000, "n_primes": int(p1e4.size),
                  "grid_halfwidth": step, "grid_points": 257,
                  "time_s": round(tA.seconds, 1),
                  "best10": [{"absP_head": v, "t": t} for v, t in bestA[:10]]},
        "passB": {"windows": 10, "primes_upto": 1_000_000, "n_primes": int(p1e6.size),
                  "grid_halfwidth": step / 128, "grid_points": 257,
                  "time_s": round(tB.seconds, 1),
                  "tail_bound_beyond_1e6": rem6,
                  "tail_bound_note": "all-integer bound (1e6)^(-3/4)/(3/4) + (1e6)^(-7/4), measured floats",
                  "best5": [{"absP_head_1e6": v, "t": t,
                             "absP_interval": [max(0.0, v - rem6), v + rem6]}
                            for v, t in bestB[:5]]},
        "best": {"absP_head_1e6": bestB[0][0], "t": bestB[0][1],
                 "absP_interval": [max(0.0, bestB[0][0] - rem6), bestB[0][0] + rem6]},
    }


