def margin_analysis(mu):
    fctx.prec = FLINT_PREC
    out = {}
    with Timer() as t:
        s = arb_from_fraction(SIGMA1)
        P = prime_zeta_arb(s, K_MOEBIUS, mu)
        r2 = arb(2) ** (-s)
        R = P - r2
        eps0 = R - r2
        head_all = arb(0)
        for p in np_primes_upto(X_HEAD - 1):
            head_all += arb(int(p)) ** (-s)
        T50 = P - head_all
        head_odd = head_all - r2
    P_lo, P_hi = arb_endpoints(P)
    r2_lo, r2_hi = arb_endpoints(r2)
    R_lo, R_hi = arb_endpoints(R)
    e_lo, e_hi = arb_endpoints(eps0)
    T_lo, T_hi = arb_endpoints(T50)
    ho_lo, ho_hi = arb_endpoints(head_odd)
    out["flint"] = {
        "backend": "python-flint (arb)",
        "precision": f"{FLINT_PREC} bits",
        "moebius_K": K_MOEBIUS,
        "time_s": round(t.seconds, 3),
        "P_at_sigma1": enclosure_record(P_lo, P_hi, 33),
        "r2": enclosure_record(r2_lo, r2_hi, 33),
        "R_total_modulus_p_ge_3": enclosure_record(R_lo, R_hi, 33),
        "eps0_budget_R_minus_r2": enclosure_record(e_lo, e_hi, 33),
        "head_odd_modulus_3_to_47": enclosure_record(ho_lo, ho_hi, 33),
        "prime_tail_T50_p_gt_47": enclosure_record(T_lo, T_hi, 33),
        "eps0_positive_decided": decided_sign(e_lo, e_hi) == 1,
        "head_cancellation_feasible": {
            "statement": "head budget (head_odd max) - (r2 - T50) equals eps0 "
                         "exactly by construction, and eps0 > 0 is decided, so "
                         "the p <= 47 head can in principle cancel the p = 2 "
                         "term with best-case tail phase",
            "decided": decided_sign(e_lo, e_hi) == 1,
        },
    }
    # iv cross-check of the central quantity
    iv.dps = IV_DPS
    with Timer() as t:
        s_iv = iv_from_fraction(SIGMA1)
        P_iv = prime_zeta_iv(s_iv, K_IV, mu)
        e_iv = P_iv - iv.mpf(2) ** (1 - s_iv)
    Pi_lo, Pi_hi = iv_endpoints(P_iv)
    ei_lo, ei_hi = iv_endpoints(e_iv)
    out["mpmath_iv"] = {
        "backend": "mpmath.iv",
        "precision": f"dps {IV_DPS}",
        "moebius_K": K_IV,
        "time_s": round(t.seconds, 3),
        "P_at_sigma1": enclosure_record(Pi_lo, Pi_hi, 14),
        "eps0_budget": enclosure_record(ei_lo, ei_hi, 14),
        "eps0_positive_decided": decided_sign(ei_lo, ei_hi) == 1,
    }
    out["cross_checks"] = {
        "P_backends_intersect": max(P_lo, Pi_lo) <= min(P_hi, Pi_hi),
        "P_flint_inside_iv": Pi_lo <= P_lo and P_hi <= Pi_hi,
        "eps0_backends_intersect": max(e_lo, ei_lo) <= min(e_hi, ei_hi),
    }
    floats = {
        "P": float((P_lo + P_hi) / 2),
        "r2": float((r2_lo + r2_hi) / 2),
        "R": float((R_lo + R_hi) / 2),
        "eps0": float((e_lo + e_hi) / 2),
        "T50": float((T_lo + T_hi) / 2),
        "head_odd": float((ho_lo + ho_hi) / 2),
    }
    return out, floats


